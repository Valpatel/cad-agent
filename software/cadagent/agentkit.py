# `cad-agent update`: the steps the one-line installer runs again. Never a network call of its own: the only one is
# the person's own `git fetch` from the checkout's origin. Nothing runs in the background or on a schedule.

STALE_DAYS = 14
DEPENDENCY_FILES = ("pyproject.toml", "uv.lock")
CHANGELOG_SECTIONS = ("Projects must change", "New", "Changed", "Fixed")
REINSTALL_LATER = 3           # exit code: the dependencies changed, and this process cannot replace itself (Windows)


class UpdateRefused(Exception):
    """The checkout is not in a state ``update`` may change: the message says why and what to do."""


def _git(root: Path, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)
    if check and r.returncode:
        raise UpdateRefused(f"git {' '.join(args)}: {(r.stderr or r.stdout).strip()}")
    return r.stdout.strip() if r.returncode == 0 else ""


def checkout_state(root: Path) -> dict:
    """Where the checkout is: its commit, branch (or the tag it is pinned at), and whether tracked files changed."""
    if not _git(root, "rev-parse", "--is-inside-work-tree", check=False):
        raise UpdateRefused(f"{root} is not a git checkout: install with the one-line installer, which clones it")
    return {"commit": _git(root, "rev-parse", "HEAD"),
            "branch": _git(root, "symbolic-ref", "-q", "--short", "HEAD", check=False),
            "tag": _git(root, "describe", "--tags", "--exact-match", "HEAD", check=False),
            "dirty": bool(_git(root, "status", "--porcelain", "--untracked-files=no"))}


FORK_HINT = ("To change cad-agent itself, fork Valpatel/cad-agent and work in a clone of your fork (git pull there "
             "yourself); keep {root} on main for updates.")


def pull(root: Path, ref: Optional[str] = None) -> dict:
    """Move the checkout to the newest main (fast-forward only), or to ``ref`` (a tag or branch, checked out
    detached). Refuses a checkout with changed tracked files, or one on another branch (than main or ``ref``) or an
    untagged commit."""
    st = checkout_state(root)
    if st["dirty"]:
        raise UpdateRefused(f"{root} has changes to tracked files: commit or stash them first. "
                            + FORK_HINT.format(root=root))
    # On main, or on the branch --ref names (what `install.sh --ref <branch>` cloned), or pinned at a tag.
    if st["branch"] and st["branch"] not in ("main", ref):
        raise UpdateRefused(f"{root} is on branch {st['branch']!r}, and updates follow main, the released channel "
                            f"(git -C {root} switch main). " + FORK_HINT.format(root=root))
    if not st["branch"] and not st["tag"]:
        raise UpdateRefused(f"{root} is at a commit that is neither main nor a release tag. "
                            + FORK_HINT.format(root=root))
    shallow = _git(root, "rev-parse", "--is-shallow-repository", check=False) == "true"
    if ref:
        if ref.startswith("-") or not re.fullmatch(r"[A-Za-z0-9._/-]+", ref):
            raise UpdateRefused(f"--ref takes a tag or branch name, e.g. v0.14.0, not {ref!r}")
        depth = ["--depth", "1"] if shallow else []
        if subprocess.run(["git", "-C", str(root), "fetch", "--quiet", *depth, "origin",
                           f"+refs/tags/{ref}:refs/tags/{ref}"], capture_output=True).returncode == 0:
            _git(root, "checkout", "--quiet", "--detach", f"refs/tags/{ref}")     # a release: pinned, detached
        else:                                                                   # a branch: follow it, fast-forward only
            _git(root, "fetch", "--quiet", "origin", f"+refs/heads/{ref}:refs/remotes/origin/{ref}")
            if _git(root, "rev-parse", "--verify", "-q", f"refs/heads/{ref}", check=False):
                _git(root, "switch", "--quiet", ref)
                if subprocess.run(["git", "-C", str(root), "merge", "--quiet", "--ff-only", f"origin/{ref}"],
                                  capture_output=True).returncode:
                    raise UpdateRefused(f"{root}'s {ref} has commits that are not on cad-agent's {ref}, so it cannot "
                                        "fast-forward. " + FORK_HINT.format(root=root))
            else:
                _git(root, "switch", "--quiet", "-c", ref, f"origin/{ref}")
    else:
        _git(root, "fetch", "--quiet", "origin", "+refs/heads/main:refs/remotes/origin/main")
        if st["branch"] != "main":                       # pinned at a tag: back to main
            if _git(root, "rev-parse", "--verify", "-q", "refs/heads/main", check=False):
                _git(root, "switch", "--quiet", "main")
            else:
                _git(root, "switch", "--quiet", "-c", "main", "origin/main")
        ff = lambda: subprocess.run(["git", "-C", str(root), "merge", "--quiet", "--ff-only", "origin/main"],
                                    capture_output=True).returncode == 0
        # A shallow clone that was pinned to a tag (fetched at depth 1) cannot see that main descends from where it
        # was: fetch main's whole history once, then decide.
        if not ff() and shallow:
            _git(root, "fetch", "--quiet", "--unshallow", "origin", "+refs/heads/main:refs/remotes/origin/main")
        if not ff():
            raise UpdateRefused(f"{root}'s main has commits that are not on cad-agent's main, so it cannot "
                                "fast-forward. " + FORK_HINT.format(root=root))
    new = _git(root, "rev-parse", "HEAD")
    changed = _git(root, "diff", "--name-only", st["commit"], new, check=False).splitlines() if new != st["commit"] else []
    return {"old": st["commit"], "new": new, "changed": changed,
            "at": ref or "main", "dependencies_changed": any(f in DEPENDENCY_FILES for f in changed)}


def _receipt_extras() -> Optional[List[str]]:
    """The extras uv recorded when it installed this cad-agent (``uv-receipt.toml`` in the tool environment), or None
    for an install uv did not make."""
    text = _text(Path(sys.prefix) / "uv-receipt.toml")
    if not text:
        return None
    try:
        import tomllib
        reqs = tomllib.loads(text).get("tool", {}).get("requirements", [])
        for req in reqs if isinstance(reqs, list) else []:
            if isinstance(req, dict) and req.get("name") == "cad-agent":
                return sorted(str(e) for e in req.get("extras", []))
    except (ImportError, ValueError):
        m = re.search(r'name\s*=\s*"cad-agent"[^}]*?extras\s*=\s*\[([^\]]*)\]', text)
        if m:
            return sorted(re.findall(r'"([^"]+)"', m.group(1)))
    return None


def installed_extras(root: Path) -> List[str]:
    """The extras this cad-agent was installed with: what uv recorded, else the extras whose active requirements are
    installed in this Python. Call it before pulling: a newer pyproject.toml may list packages not installed yet."""
    receipt = _receipt_extras()
    if receipt is not None:
        return receipt
    import importlib.metadata as md
    from packaging.requirements import Requirement
    try:
        import tomllib
    except ImportError:                                    # Python 3.10: read the table by hand
        tomllib = None
    text = _text(root / "pyproject.toml")
    if tomllib:
        try:
            extras = tomllib.loads(text).get("project", {}).get("optional-dependencies", {})
        except ValueError:                                 # a damaged pyproject.toml: update refuses it next
            return []
    else:
        block = text.split("[project.optional-dependencies]", 1)[-1].split("\n[", 1)[0]
        extras = {m.group(1): re.findall(r'"([^"]+)"', m.group(2))
                  for m in re.finditer(r"^(\w[\w-]*)\s*=\s*\[(.*?)\]", block, re.S | re.M)}
    have = []
    for name, reqs in extras.items():
        requirements = [Requirement(r) for r in reqs]
        dists = [r.name for r in requirements if r.marker is None or r.marker.evaluate({'extra': name})]
        try:
            for d in dists:
                md.version(d)
        except md.PackageNotFoundError:
            continue
        if dists:
            have.append(name)
    return sorted(have)


def _uv_tool_env() -> bool:
    """This cad-agent runs from `uv tool install` (its environment has uv's receipt)."""
    return (Path(sys.prefix) / "uv-receipt.toml").is_file()


def reinstall_command(root: Path, extras: List[str]) -> List[str]:
    """How to reinstall this cad-agent with ``extras``: uv's tool install when that is how it was installed, else
    pip into the running environment (an older, venv install)."""
    spec = f"{root}[{','.join(extras)}]" if extras else str(root)
    if _uv_tool_env() and shutil.which("uv"):
        return ["uv", "tool", "install", "--quiet", "--force", "--editable", "--python",
                f"{sys.version_info.major}.{sys.version_info.minor}", spec]
    return [sys.executable, "-m", "pip", "install", "--quiet", "-e", spec]


def _pending_file(root: Path) -> Optional[Path]:
    git_dir = _git(root, "rev-parse", "--absolute-git-dir", check=False)
    return Path(git_dir) / "cad-agent-reinstall-pending" if git_dir else None


def reinstall_pending(root: Path, extras: Optional[List[str]] = None, clear: bool = False) -> Optional[List[str]]:
    """The extras of a reinstall that was started and has not finished (it failed, or install.ps1 has not run it yet),
    so the next update tries again with the same extras; None when nothing is pending. ``extras`` records one, ``clear``
    forgets it. The marker is a small JSON file in the checkout's .git folder."""
    marker = _pending_file(root)
    if marker is None:
        return None
    if clear:
        marker.unlink(missing_ok=True)
    elif extras is not None:
        marker.write_text(json.dumps({"reinstall": "started by cad-agent update, not finished", "extras": extras}) + "\n")
    try:
        return list(json.loads(marker.read_text()).get("extras", []))
    except (OSError, ValueError, AttributeError):
        return [] if marker.exists() else None


def release_notes(root: Path, old: str) -> List[dict]:
    """The CHANGELOG releases the checkout gained since ``old``: [{version, sections: {name: [bullets]}}], newest
    first. Each bullet is one line, as the release tool writes them."""
    def releases(text: str) -> Dict[str, List[str]]:
        out, cur = {}, None
        for line in text.splitlines():
            m = re.match(r"^## (v\d[^\s]*)", line)
            if m:
                cur = m.group(1)
                out[cur] = []
            elif line.startswith("## "):
                cur = None
            elif cur:
                out[cur].append(line)
        return out
    now = releases(_text(root / "CHANGELOG.md"))
    before = releases(_git(root, "show", f"{old}:CHANGELOG.md", check=False))
    notes = []
    for version, lines in now.items():
        if version in before:
            continue
        sections: Dict[str, List[str]] = {}
        cur = None
        for line in lines:
            m = re.match(r"^\*\*(.+?)\*\*:?\s*$", line.strip())
            if m and m.group(1).rstrip(":") in CHANGELOG_SECTIONS:
                cur = m.group(1).rstrip(":")
                sections.setdefault(cur, [])
            elif cur and line.startswith("- "):
                sections[cur].append(line[2:].strip())
            elif cur and line.startswith("  ") and sections.get(cur):
                sections[cur][-1] += " " + line.strip()
        notes.append({"version": version, "sections": sections})
    return notes


def notes_lines(notes: List[dict], width: int = 110) -> List[str]:
    """What `update` prints: every "Projects must change" item in full, first; then each release's other sections
    as counts and their first lines."""
    lines = []
    must = [(n["version"], b) for n in notes for b in n["sections"].get("Projects must change", [])]
    if must:
        lines.append("Projects must change:")
        lines += [f"  {v}: {b}" for v, b in must]
    for n in notes:
        counts = ", ".join(f"{len(n['sections'][s])} {s.lower()}" for s in CHANGELOG_SECTIONS[1:] if n["sections"].get(s))
        lines.append(f"{n['version']}: {counts or 'no entries'}")
        for b in n["sections"].get("New", [])[:5]:
            lines.append("  + " + (b if len(b) <= width else b[:width - 1] + "…"))
    if notes:
        lines.append("All of it: CHANGELOG.md in the checkout.")
    return lines


def _version_tuple(v: str) -> Optional[Tuple[int, ...]]:
    m = re.match(r"v?(\d+)\.(\d+)(?:\.(\d+))?", v or "")
    return tuple(int(x or 0) for x in m.groups()) if m else None


def version_ok(have: str, need: str) -> Optional[bool]:
    """Whether version ``have`` is at least ``need``; None when either cannot be read (0+unknown)."""
    h, n = _version_tuple(have), _version_tuple(need)
    return None if h is None or n is None else h >= n


def project_advice(project_root: Path, kit_version: str, results_name: str = "cad-agent-results.json") -> List[str]:
    """What a project should do after an update, from what it records: its ``cad: cad-agent:`` minimum, and the
    version its last ``cad-agent all`` wrote into exports/<results>."""
    import yaml
    lines = []
    try:
        cad = (yaml.safe_load((project_root / "cad-agent.yaml").read_text()) or {}).get("cad") or {}
    except (OSError, yaml.YAMLError):
        return lines
    need = cad.get("cad-agent")
    if isinstance(need, float):
        lines.append(f"write cad-agent: as a string in cad-agent.yaml (\"{need}\" in quotes): YAML reads {need} as a "
                     "number, so 0.10 becomes 0.1")
    elif need and version_ok(kit_version, str(need)) is False:
        lines.append(f"this project needs cad-agent {need} or newer and this is {kit_version}: update to it, or pin "
                     "it with --ref")
    exports = project_root / str(cad.get("exports_dir", "exports"))
    try:
        built = json.loads((exports / results_name).read_text()).get("cad_agent")
    except (OSError, ValueError):
        built = None
    if built and built != kit_version:
        lines.append(f"this project was last built with cad-agent {built}; this is {kit_version}. Make the changes "
                     "listed under \"Projects must change\", then run `cad-agent all`")
    elif not built:
        lines.append("this project has no record of the cad-agent that built it: run `cad-agent all`")
    return lines


def staleness(root: Path, now: Optional[float] = None) -> Optional[str]:
    """A local note when the checkout's last commit is older than STALE_DAYS (nothing is asked of any server)."""
    stamp = _git(root, "log", "-1", "--format=%ct", check=False) if (root / ".git").exists() else ""
    if not stamp.isdigit():
        return None
    if not _git(root, "symbolic-ref", "-q", "HEAD", check=False) and _git(root, "describe", "--tags", "--exact-match",
                                                                          "HEAD", check=False):
        return None                                      # pinned to a release on purpose (--ref vX.Y.Z)
    import time
    days = int(((now or time.time()) - int(stamp)) // 86400)
    if days <= STALE_DAYS:
        return None
    return f"this cad-agent's last commit is {days} days old: `cad-agent update` gets the newest release"
