"""Install cad-agent's skills and subagents for the agent harnesses (``cad-agent agents``).

The kit lives in the cad-agent checkout: ``.agents/skills/<name>/SKILL.md`` (the open agent-skill format both tools read) and
``.agents/agents/<name>.md`` (Claude Code subagents: frontmatter ``name``, ``description``, ``tools``, then the prompt).
``README.md`` is reserved for the human folder map and is not installed as a role.

``install`` puts them where the tools look, for the current user:

- Claude Code: ``~/.claude/skills/<skill>`` and ``~/.claude/agents/<agent>.md``
- every other harness (Codex, Copilot CLI, Cursor, Gemini CLI, opencode): ``~/.agents/skills/<skill>``, the shared
  folder they all read. They have no subagent files, so each agent is also written there as a skill
  ``~/.agents/skills/<agent>/SKILL.md`` (generated, marked, rewritten on every install) to run in a separate session.
  Installs before this used ``~/.codex/skills``; ``install`` removes what it put there (``migrate``), because Codex
  lists a skill twice when it is in both folders.

``install`` also removes its own links that point at a skill or agent the kit no longer has (``prune``), and
``uninstall`` removes everything it put anywhere. Where a link cannot be made (Windows without Developer Mode), it
copies instead.

Skills and agents are symlinked to the checkout by default, so ``git pull`` updates them; ``--copy`` copies instead
(instructions and bundled files only; links to repository guides still need the checkout). Link to a long-lived
checkout, not a feature worktree that will be removed. Only
what this module made is ever replaced (links into a cad-agent checkout, generated files, marked copies); anything else
at a destination, including the user's own links, is reported as a conflict and left alone.

Everything is installed for everyone (#282). A skill or agent that needs something a person may lack (``gh`` logged
in, write access to the repository, a toolchain) names it in its frontmatter as ``metadata: {requires: "gh git"}``,
and what only some of its steps use as ``optional: "rsync"`` with ``optional-for:`` naming those steps (the Agent Skills format keeps extra fields under
``metadata``). It says the same in a ``> **Needs:**`` line at the top of its text. ``readiness`` checks what this computer can tell without any network call, and the CLI says which skills
cannot be used yet and why, and what it cannot check from here.
"""
from __future__ import annotations

import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple

MARKER = "<!-- generated by `cad-agent agents install` from .agents/agents/{name}.md: edit that file, not this one -->"
KIT_SKILLS = ".agents/skills"
KIT_AGENTS = ".agents/agents"
TARGETS = ("claude", "agents")
ALIASES = {"codex": "agents"}      # the shared folder serves Codex too; --target codex keeps working


@dataclass
class Item:
    kind: str           # 'skill' | 'agent'
    name: str
    path: Path          # skill folder or agent file
    description: str
    requires: Tuple[str, ...] = field(default=())   # REQUIREMENTS keys, from frontmatter metadata.requires
    optional: Tuple[str, ...] = field(default=())   # ...that only some of its steps use (metadata.optional)
    optional_for: str = ""                          # which steps those are, in a few words (metadata.optional-for)


def _on_path(*names: str) -> bool:
    return any(shutil.which(n) for n in names)


def _gh_logged_in() -> Optional[str]:
    if not _on_path("gh"):
        return "`gh` is not on PATH: install the GitHub CLI (cli.github.com), then run `gh auth login`"
    try:   # reads gh's stored token, which is thrown away: no network call
        ok = subprocess.run(["gh", "auth", "token"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                            timeout=20).returncode == 0
    except (OSError, subprocess.SubprocessError):
        ok = False
    return None if ok else "`gh` is not logged in: run `gh auth login`"


# Google Chrome itself: cadagent.mechanical.mcmaster launches Playwright's "chrome" channel, so Chromium does not count.
CHROME = ("google-chrome", "google-chrome-stable", "chrome")
# Only the places Playwright itself looks for the "chrome" channel (a per-user macOS app is not one of them).
CHROME_APPS = ("/Applications/Google Chrome.app", "/opt/google/chrome/chrome",
               r"C:\Program Files\Google\Chrome\Application\chrome.exe",
               r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
               r"%LOCALAPPDATA%\Google\Chrome\Application\chrome.exe")


def _playwright() -> Optional[str]:
    missing = []
    if importlib.util.find_spec("playwright") is None:
        missing.append(f"Playwright is not installed in this Python (`\"{sys.executable}\" -m pip install playwright`)")
    if not (_on_path(*CHROME) or any(Path(os.path.expandvars(p)).expanduser().exists() for p in CHROME_APPS)):
        missing.append("Google Chrome was not found")
    return "; ".join(missing) or None


def _node() -> Optional[str]:
    """Check the existing site/SCADA toolchain floor without fetching packages."""
    if not _on_path("node"):
        return "`node` is not on PATH: install Node.js 22 or newer"
    try:
        result = subprocess.run(["node", "--version"], capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return "`node --version` failed: Node.js 22 or newer is required"
    version = re.fullmatch(r"v(\d+)\.\d+\.\d+\s*", result.stdout)
    if result.returncode or not version or int(version[1]) < 22:
        return "Node.js 22 or newer is required by the site and SCADA maintenance tools"
    return None


def _scada_browser() -> Optional[str]:
    """Find the Python capture dependency and a local Chromium; do not launch or download it.

    The capture tools default to ``chromium`` on PATH, else Playwright's own
    installed Chromium. This checks that same choice. A successful browser test
    is still needed to establish OS libraries, permissions and rendering behavior.
    """
    if importlib.util.find_spec("playwright") is None:
        return "Python Playwright is missing: install tools/webkit/scada/ui/requirements.txt in this Python"
    if shutil.which("chromium"):
        return None
    code = ("from playwright.sync_api import sync_playwright\n"
            "with sync_playwright() as p: print(p.chromium.executable_path)\n")
    try:
        result = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, timeout=10)
        executable = result.stdout.strip()
        if result.returncode == 0 and executable and len(executable) < 4096 and Path(executable).is_file():
            return None
    except (OSError, subprocess.SubprocessError):
        pass
    return "Chromium was not found: install a local chromium binary or run this Python's `-m playwright install chromium`"


@dataclass(frozen=True)
class Requirement:
    label: str                                       # how a Needs line and the notice name it
    check: Optional[Callable[[], Optional[str]]]     # the reason it is missing, or None; no check: cannot tell here


REQUIREMENTS: Dict[str, Requirement] = {
    "git": Requirement("`git`", lambda: None if _on_path("git") else "`git` is not on PATH"),
    "gh": Requirement("`gh` logged in", _gh_logged_in),
    "ssh": Requirement("`ssh`", lambda: None if _on_path("ssh") else "`ssh` is not on PATH"),
    "rsync": Requirement("`rsync`", lambda: None if _on_path("rsync") else "`rsync` is not on PATH"),
    "playwright": Requirement("Playwright and Google Chrome", _playwright),
    "node": Requirement("`node` 22 or newer", _node),
    "npm": Requirement("`npm`", lambda: None if _on_path("npm") else "`npm` is not on PATH"),
    "scada-browser": Requirement("Python Playwright and local Chromium", _scada_browser),
    "write-access": Requirement("write access to the repository it works in", None),
    "compute-host": Requirement("a compute host you can reach over `ssh`", None),
}


def kit_root(source: Optional[Path] = None) -> Path:
    """The checkout holding the canonical .agents/skills/ and .agents/agents/: ``source``, else the one this package is installed from (editable)."""
    root = Path(source).expanduser().resolve() if source else Path(__file__).resolve().parents[2]
    if not (root / KIT_SKILLS).is_dir() or not (root / KIT_AGENTS).is_dir():
        raise FileNotFoundError(f"{root} has no .agents/skills/ and .agents/agents/ folders: install cad-agent from a checkout "
                                "(pip install -e) or pass --source <cad-agent checkout>")
    return root


def _frontmatter(text: str, where: Path) -> Dict[str, str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{where}: no frontmatter (--- name/description ---)")
    import yaml
    try:
        fields = yaml.safe_load(m.group(1))
    except yaml.YAMLError as exc:
        raise ValueError(f"{where}: frontmatter is not valid YAML (quote a description that contains ': '): {exc}") from None
    if not isinstance(fields, dict):
        raise ValueError(f"{where}: frontmatter must be a mapping")
    for line in m.group(1).splitlines():   # in plain YAML " #" starts a comment: the rest of the line would be lost
        key, _, raw = line.partition(":")
        raw = raw.strip()
        if key in ("name", "description") and raw[:1] not in ("'", '"', "|", ">") and " #" in raw:
            raise ValueError(f"{where}: {key} contains ' #', which YAML reads as a comment: quote it")
    for key in ("name", "description"):
        if not isinstance(fields.get(key), str) or not fields[key].strip():
            raise ValueError(f"{where}: frontmatter needs {key}")
    return fields


def _requires(fields: Dict, where: Path) -> Tuple[Tuple[str, ...], Tuple[str, ...], str]:
    """(requires, optional, optional-for) from the frontmatter's metadata: the first two are each one string of
    REQUIREMENTS names; optional-for says which steps the optional ones serve."""
    meta = fields.get("metadata") or {}
    if not isinstance(meta, dict):
        raise ValueError(f"{where}: frontmatter metadata must be a mapping")
    out = []
    for key in ("requires", "optional"):
        raw = meta.get(key, "")
        if not isinstance(raw, str):
            raise ValueError(f"{where}: metadata.{key} is one string of names, e.g. \"gh git\"")
        names = tuple(raw.split())
        unknown = sorted(set(names) - set(REQUIREMENTS))
        if unknown:
            raise ValueError(f"{where}: metadata.{key} names {unknown}; known: {sorted(REQUIREMENTS)}")
        out.append(names)
    every = out[0] + out[1]
    if len(set(every)) != len(every):
        raise ValueError(f"{where}: metadata names a need twice: {sorted(n for n in set(every) if every.count(n) > 1)}")
    steps = meta.get("optional-for", "")
    if not isinstance(steps, str) or (steps and not out[1]):
        raise ValueError(f"{where}: metadata.optional-for is a few words, and only with metadata.optional")
    return out[0], out[1], steps.strip()


def items(root: Path) -> List[Item]:
    """Every skill and agent in the kit, checked: names match their folder/file and are unique across both kinds."""
    found = []
    for folder in sorted(p for p in (root / KIT_SKILLS).iterdir() if (p / "SKILL.md").is_file()):
        fm = _frontmatter((folder / "SKILL.md").read_text(), folder / "SKILL.md")
        if fm["name"] != folder.name:
            raise ValueError(f"{folder}/SKILL.md: name {fm['name']!r} does not match its folder")
        found.append(Item("skill", folder.name, folder, fm["description"], *_requires(fm, folder / "SKILL.md")))
    for path in sorted((root / KIT_AGENTS).glob("*.md")):
        if path.name == "README.md":  # Human folder map, never an installed role or generated skill.
            continue
        fm = _frontmatter(path.read_text(), path)
        if fm["name"] != path.stem:
            raise ValueError(f"{path}: name {fm['name']!r} does not match its file name")
        found.append(Item("agent", path.stem, path, fm["description"], *_requires(fm, path)))
    names = [i.name for i in found]
    clashes = sorted({n for n in names if names.count(n) > 1})
    if clashes:
        raise ValueError(f"a skill and an agent share a name: {clashes}")
    return found


def _listed(names: Tuple[str, ...]) -> str:
    """The needs' labels as one phrase."""
    labels = [REQUIREMENTS[r].label for r in names]
    return labels[0] if len(labels) == 1 else ", ".join(labels[:-1]) + " and " + labels[-1]


def needs_line(item: Item) -> str:
    """The ``> **Needs:**`` line an item with needs opens with (after its title, if it has one); "" without needs."""
    if not item.requires and not item.optional:
        return ""
    if item.requires and item.optional:
        what = (f"{_listed(item.requires)}; {_listed(item.optional)} for {item.optional_for or 'some steps'}. "
                "`cad-agent agents install` says which of these this computer lacks. Without "
                f"{_listed(item.optional)}, skip {'that step' if item.optional_for else 'those steps'}; without the "
                "rest, do not use it.")
    elif item.requires:
        what = (f"{_listed(item.requires)}. `cad-agent agents install` says which of these this computer lacks; "
                "without them, do not use it.")
    else:
        what = (f"nothing, except {_listed(item.optional)} for {item.optional_for or 'some steps'}. `cad-agent agents "
                "install` says whether this computer has them; without them, skip those steps.")
    return f"> **Needs:** {what}"


def readiness(root: Path, checks: Optional[Dict[str, Optional[str]]] = None) -> List[dict]:
    """For each item with needs: what is missing here and why (``missing``: it can't be used; ``partial``: some steps
    can't run), and what cannot be checked here. ``checks`` maps a need to its reason (None: met), for tests;
    otherwise each is checked once, locally, with no network call."""
    found: Dict[str, Optional[str]] = dict(checks or {})

    def reason(r: str) -> Optional[str]:
        if r not in found:
            found[r] = REQUIREMENTS[r].check()
        return found[r]
    rows = []
    for item in items(root):
        row = {"kind": item.kind, "name": item.name, "missing": [], "partial": [], "unchecked": []}
        for r in item.requires + item.optional:
            if REQUIREMENTS[r].check is None:
                row["unchecked"].append(REQUIREMENTS[r].label)
            elif reason(r):
                row["missing" if r in item.requires else "partial"].append(found[r])
        if row["missing"] or row["partial"] or row["unchecked"]:
            rows.append(row)
    return rows


def notice(rows: List[dict]) -> List[str]:
    """The lines the CLI prints after install and list: what can't be used yet and why, what can be used with some
    steps left out, then what cannot be checked here. Nothing when there is nothing to say."""
    lines = []
    for key, head in (("missing", "agents: you can't use these yet:"),
                      ("partial", "agents: you can use these, but some of their steps can't run yet:")):
        rows_ = [r for r in rows if r[key]]
        if rows_:
            lines.append(head)
            lines += [f"  {r['kind']} {r['name']}: " + "; ".join(r[key]) for r in rows_]
    unchecked: Dict[str, List[str]] = {}
    for r in rows:
        for label in r["unchecked"]:
            unchecked.setdefault(label, []).append(r["name"])
    if unchecked:
        lines.append(("agents: these" if lines else "agents: nothing is missing here. These") +
                     " also need what cad-agent can't check from here:")
        lines += [f"  {label}: {', '.join(names)}" for label, names in unchecked.items()]
    return lines


def codex_agent_skill(item: Item) -> str:
    """An agent as a skill for harnesses without subagent files: same name and description, the prompt as the body,
    run in a separate session. (The name is from when Codex was the only one.)"""
    body = re.sub(r"\A---\n.*?\n---\n", "", item.path.read_text(), count=1, flags=re.S).lstrip()
    import yaml
    head = yaml.safe_dump({"name": item.name, "description": item.description}, sort_keys=False, width=1000)
    return (f"---\n{head}---\n\n{MARKER.format(name=item.name)}\n\n"
            "Run this only in its own session, separate from the session that did the work: do not use it on "
            "work you wrote yourself in this session. Whoever starts the session gives the inputs the instructions "
            "below ask for (for example a PR URL and a checkout path).\n\n" + body)


def target_dirs(home: Path) -> Dict[str, Path]:
    """Where each harness looks, and the Codex folder earlier installs used (``$CODEX_HOME/skills`` when set and
    installing into your own home, else ``~/.codex/skills``), which ``migrate`` empties of what we put there."""
    codex = Path(os.environ["CODEX_HOME"]).expanduser() if os.environ.get("CODEX_HOME") and home == Path.home() else home / ".codex"
    return {"claude_skills": home / ".claude/skills", "claude_agents": home / ".claude/agents",
            "agents_skills": home / ".agents/skills", "legacy_codex_skills": codex / "skills"}


def _targets(targets) -> Tuple[str, ...]:
    out = tuple(dict.fromkeys(ALIASES.get(t, t) for t in targets))
    unknown = [t for t in out if t not in TARGETS]
    if unknown:
        raise ValueError(f"unknown target {unknown}; use {', '.join(TARGETS)} (codex is the same as agents)")
    return out


def _check_dirs(dirs: Dict[str, Path], root: Path, targets) -> None:
    """Refuse destinations that resolve into the kit itself, or a shared skills folder that is the Claude one (the
    generated agent skills would then shadow Claude's own subagents)."""
    kit = [(root / KIT_SKILLS).resolve(), (root / KIT_AGENTS).resolve()]
    for name, folder in dirs.items():
        if name == "legacy_codex_skills":     # only emptied of our own entries, never installed into
            continue
        real = folder.resolve()
        if any(real == k or k in real.parents for k in kit):
            raise ValueError(f"{folder} resolves into the kit itself ({real}); point it somewhere else")
    if "claude" in targets and "agents" in targets and dirs["agents_skills"].resolve() == dirs["claude_skills"].resolve():
        raise ValueError(f"{dirs['agents_skills']} is the same folder as {dirs['claude_skills']}: install with "
                         "--target claude (the other harnesses then see the skills through it, but not the agents)")


def _plan(home: Path, root: Path, targets) -> List[tuple]:
    """(item, destination, how) for each target: how is 'link' or 'generate'."""
    targets = _targets(targets)
    dirs = target_dirs(home)
    _check_dirs(dirs, root, targets)
    plan = []
    for item in items(root):
        if "claude" in targets:
            if item.kind == "skill":
                plan.append((item, dirs["claude_skills"] / item.name, "link"))
            else:
                plan.append((item, dirs["claude_agents"] / f"{item.name}.md", "link"))
        if "agents" in targets:
            plan.append((item, dirs["agents_skills"] / item.name, "link" if item.kind == "skill" else "generate"))
    return plan


COPY_MARK = ".installed-by-cad-agent"


def _text(path: Path) -> str:
    try:
        return path.read_text()
    except (UnicodeDecodeError, OSError):
        return ""


def _kit_link(dest: Path) -> bool:
    """A link this module made: it points at <kit>/skills/<name> or <kit>/agents/<name>.md of a cad-agent checkout
    (this one or an older one). A live kit is recognized independently of its directory name, even when a move
    removed the old target. A removed worktree retains the cad-agent-name fallback. Other links are the user's."""
    target = Path(os.path.normpath(dest.parent / os.readlink(dest)))
    if target.parent.name not in ("skills", "agents"):
        return False
    owner = target.parent.parent
    kit = owner.parent if owner.name == ".agents" else owner
    source = (kit / "src/cadagent").is_dir() or (kit / "software/cadagent").is_dir()
    assets = ((kit / KIT_SKILLS).is_dir() and (kit / KIT_AGENTS).is_dir()) or \
             ((kit / "skills").is_dir() and (kit / "agents").is_dir())
    if source and assets:  # A move can remove the target inside a still-live, arbitrarily named checkout.
        return True
    return not target.exists() and "cad-agent" in kit.name


def _ours(dest: Path) -> bool:
    """Something this module put there: a link into a cad-agent kit, a generated Codex agent skill, or a marked copy."""
    if dest.is_symlink():
        return _kit_link(dest)
    if dest.is_dir():
        return (dest / COPY_MARK).is_file() or "generated by `cad-agent agents install`" in _text(dest / "SKILL.md")
    return dest.is_file() and COPY_MARK in _text(dest)


def _copy_current(item: Item, dest: Path) -> bool:
    """A marked copy still matches the kit."""
    if item.path.is_dir():
        sources = {p.relative_to(item.path): p for p in item.path.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
        copies = {p.relative_to(dest): p for p in dest.rglob("*") if p.is_file() and p.name != COPY_MARK}
        return sources.keys() == copies.keys() and all(sources[k].read_bytes() == copies[k].read_bytes() for k in sources)
    return _text(dest).startswith(item.path.read_text())


def status(home: Path, root: Path, targets=TARGETS) -> List[dict]:
    rows = []
    for item, dest, how in _plan(home, root, targets):
        if dest.is_symlink():
            state = "installed" if dest.resolve() == item.path.resolve() else f"links elsewhere ({dest.resolve()})"
        elif not dest.exists():
            state = "missing"
        elif not _ours(dest):
            state = "conflict (not installed by cad-agent)"
        elif how == "generate":
            state = "installed" if _text(dest / "SKILL.md") == codex_agent_skill(item) else "out of date"
        else:
            state = "copied" if _copy_current(item, dest) else "copied, out of date"
        rows.append({"kind": item.kind, "name": item.name, "dest": str(dest), "state": state})
    return rows


def _remove(dest: Path) -> None:
    if dest.is_symlink() or dest.is_file():
        dest.unlink()
    elif dest.is_dir():
        shutil.rmtree(dest)


def _entries(folder: Path) -> List[Path]:
    try:
        return sorted(folder.iterdir())
    except OSError:
        return []


def migrate(home: Path, dry_run: bool = False) -> List[str]:
    """Remove what earlier installs put in the old Codex folder (links into a cad-agent checkout, generated agent
    skills, marked copies): it now goes in ~/.agents/skills, which Codex also reads. Anything else there stays."""
    dirs = target_dirs(home)
    old = dirs["legacy_codex_skills"]
    if not old.is_dir() or old.resolve() in (dirs["agents_skills"].resolve(), dirs["claude_skills"].resolve()):
        return []
    gone = [d for d in _entries(old) if _ours(d)]
    if not dry_run:
        for d in gone:
            _remove(d)
    return [f"remove {d} (moved to {dirs['agents_skills']})" for d in gone]


def prune(home: Path, root: Path, targets=TARGETS, dry_run: bool = False) -> List[str]:
    """Remove our own entries that point at nothing any more: dangling links into a cad-agent checkout (a skill the
    kit dropped, a removed worktree), and generated or copied items whose name the kit no longer has."""
    names = {i.name for i in items(root)}
    dirs, targets = target_dirs(home), _targets(targets)
    folders = ([dirs["claude_skills"], dirs["claude_agents"]] if "claude" in targets else []) + \
              ([dirs["agents_skills"]] if "agents" in targets else [])
    gone = []
    for folder in folders:
        for d in _entries(folder):
            name = d.name[:-3] if d.name.endswith(".md") and folder == dirs["claude_agents"] else d.name
            if not _ours(d):
                continue
            if (d.is_symlink() and not d.exists()) or (not d.is_symlink() and name not in names):
                gone.append(d)
    if not dry_run:
        for d in gone:
            _remove(d)
    return [f"remove {d} (no longer in the kit)" for d in gone]


def install(home: Path, root: Path, targets=TARGETS, copy: bool = False, dry_run: bool = False) -> dict:
    """Install the kit. Returns {'done': [...], 'conflicts': [...], 'removed': [...]}. Only what this module made is
    replaced or removed; anything else at a destination is a conflict and left untouched. A link that cannot be made
    (Windows without Developer Mode) becomes a copy."""
    done, conflicts = [], []
    plan = _plan(home, root, targets)              # checks the folders first, before anything is removed
    removed = migrate(home, dry_run) + prune(home, root, targets, dry_run)
    for item, dest, how in plan:
        if (dest.exists() or dest.is_symlink()) and not _ours(dest):
            conflicts.append(str(dest))
            continue
        mode = "generate" if how == "generate" else "copy" if copy else "link"
        if dry_run:
            done.append(f"{mode} {dest}")
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        _remove(dest)
        if mode == "link":
            try:
                dest.symlink_to(item.path.resolve(), target_is_directory=item.path.is_dir())
            except OSError:                    # no symlink rights (Windows without Developer Mode): copy instead
                mode = "copy"
        if mode == "generate":
            dest.mkdir()
            (dest / "SKILL.md").write_text(codex_agent_skill(item))
        elif mode == "copy" and item.path.is_dir():
            shutil.copytree(item.path, dest, ignore=shutil.ignore_patterns("__pycache__"))
            (dest / COPY_MARK).write_text(f"copied from {item.path}; reinstall with cad-agent agents install --copy\n")
        elif mode == "copy":
            dest.write_text(item.path.read_text() + f"\n<!-- {COPY_MARK}: copied from {item.path} -->\n")
        done.append(f"{mode} {dest}")
    return {"done": done, "conflicts": conflicts, "removed": removed}


def uninstall(home: Path, dry_run: bool = False) -> List[str]:
    """Remove everything this module put in any of the folders (links, generated skills, marked copies)."""
    gone = [d for folder in target_dirs(home).values() for d in _entries(folder) if _ours(d)]
    if not dry_run:
        for d in gone:
            _remove(d)
    return [f"remove {d}" for d in gone]


def copies_installed(home: Path) -> bool:
    """Whether an earlier install copied rather than linked (``--copy``, or Windows), so updates keep copying."""
    return any((d / COPY_MARK).is_file() or (d.is_file() and COPY_MARK in _text(d))
               for folder in target_dirs(home).values() for d in _entries(folder) if not d.is_symlink())


def worktree_warning(root: Path) -> Optional[str]:
    """A warning when the kit root is a linked git worktree (its .git is a file): it may be removed later."""
    git = root / ".git"
    if git.is_file():
        return (f"{root} is a git worktree; links into it break when it is removed. Prefer the main checkout "
                "(--source) or --copy.")
    return None


