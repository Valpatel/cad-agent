"""Install cad-agent's agent workflow kit for Claude Code and Codex (``cad-agent agents``).

The kit lives in the cad-agent checkout: ``skills/<name>/SKILL.md`` (the open agent-skill format both tools read) and
``agents/<name>.md`` (Claude Code subagents: frontmatter ``name``, ``description``, ``tools``, then the prompt).

``install`` puts them where the tools look, for the current user:

- Claude Code: ``~/.claude/skills/<skill>`` and ``~/.claude/agents/<agent>.md``
- Codex: ``~/.codex/skills/<skill>``; Codex has no subagent files, so each agent is also written as a skill
  ``~/.codex/skills/<agent>/SKILL.md`` (generated, marked, rewritten on every install) to run in a separate session

Skills and agents are symlinked to the checkout by default, so ``git pull`` updates them; ``--copy`` copies instead
(for a checkout that will move). Link to a long-lived checkout, not a feature worktree that will be removed. An
existing file or folder that is not a link and not generated by this module is never overwritten: it is reported as a
conflict.
"""
from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

MARKER = "<!-- generated by `cad-agent agents install` from agents/{name}.md: edit that file, not this one -->"
TARGETS = ("claude", "codex")


@dataclass
class Item:
    kind: str           # 'skill' | 'agent'
    name: str
    path: Path          # skill folder or agent file
    description: str


def kit_root(source: Optional[Path] = None) -> Path:
    """The checkout holding skills/ and agents/: ``source``, else the one this package is installed from (editable)."""
    root = Path(source).expanduser().resolve() if source else Path(__file__).resolve().parents[2]
    if not (root / "skills").is_dir() or not (root / "agents").is_dir():
        raise FileNotFoundError(f"{root} has no skills/ and agents/ folders: install cad-agent from a checkout "
                                "(pip install -e) or pass --source <cad-agent checkout>")
    return root


def _frontmatter(text: str, where: Path) -> Dict[str, str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{where}: no frontmatter (--- name/description ---)")
    import yaml
    try:
        fields = yaml.safe_load(m.group(1))
    except yaml.YAMLError as exc:
        raise ValueError(f"{where}: frontmatter is not valid YAML (quote a description that contains ': '): {exc}") from None
    if not isinstance(fields, dict):
        raise ValueError(f"{where}: frontmatter must be a mapping")
    for key in ("name", "description"):
        if not isinstance(fields.get(key), str) or not fields[key].strip():
            raise ValueError(f"{where}: frontmatter needs {key}")
    return fields


def items(root: Path) -> List[Item]:
    """Every skill and agent in the kit, checked: names match their folder/file and are unique across both kinds."""
    found = []
    for folder in sorted(p for p in (root / "skills").iterdir() if (p / "SKILL.md").is_file()):
        fm = _frontmatter((folder / "SKILL.md").read_text(), folder / "SKILL.md")
        if fm["name"] != folder.name:
            raise ValueError(f"{folder}/SKILL.md: name {fm['name']!r} does not match its folder")
        found.append(Item("skill", folder.name, folder, fm["description"]))
    for path in sorted((root / "agents").glob("*.md")):
        fm = _frontmatter(path.read_text(), path)
        if fm["name"] != path.stem:
            raise ValueError(f"{path}: name {fm['name']!r} does not match its file name")
        found.append(Item("agent", path.stem, path, fm["description"]))
    names = [i.name for i in found]
    clashes = sorted({n for n in names if names.count(n) > 1})
    if clashes:
        raise ValueError(f"a skill and an agent share a name: {clashes}")
    return found


def codex_agent_skill(item: Item) -> str:
    """An agent as a Codex skill: same name and description, the prompt as the body, run in a separate session."""
    body = re.sub(r"\A---\n.*?\n---\n", "", item.path.read_text(), count=1, flags=re.S).lstrip()
    import yaml
    head = yaml.safe_dump({"name": item.name, "description": item.description}, sort_keys=False, width=1000)
    return (f"---\n{head}---\n\n{MARKER.format(name=item.name)}\n\n"
            "Run this as its own Codex session (a separate agent from the one that did the work), "
            "with the inputs below.\n\n" + body)


def _plan(home: Path, root: Path, targets) -> List[tuple]:
    """(item, destination, how) for each target: how is 'link' or 'generate'."""
    plan = []
    for item in items(root):
        if "claude" in targets:
            if item.kind == "skill":
                plan.append((item, home / ".claude/skills" / item.name, "link"))
            else:
                plan.append((item, home / ".claude/agents" / f"{item.name}.md", "link"))
        if "codex" in targets:
            plan.append((item, home / ".codex/skills" / item.name, "link" if item.kind == "skill" else "generate"))
    return plan


COPY_MARK = ".installed-by-cad-agent"


def _ours(dest: Path) -> bool:
    """Something this module put there: a link, a generated Codex agent skill, or a copy carrying the copy mark."""
    if dest.is_symlink():
        return True
    if dest.is_dir():
        skill = dest / "SKILL.md"
        return (dest / COPY_MARK).is_file() or (skill.is_file() and "generated by `cad-agent agents install`" in skill.read_text())
    return dest.is_file() and COPY_MARK in dest.read_text()


def status(home: Path, root: Path, targets=TARGETS) -> List[dict]:
    rows = []
    for item, dest, how in _plan(home, root, targets):
        if dest.is_symlink():
            state = "installed" if dest.resolve() == item.path.resolve() else f"links elsewhere ({dest.resolve()})"
        elif not dest.exists():
            state = "missing"
        elif not _ours(dest):
            state = "conflict (not installed by cad-agent)"
        elif how == "generate":
            state = "installed" if (dest / "SKILL.md").read_text() == codex_agent_skill(item) else "out of date"
        else:
            state = "copied"
        rows.append({"kind": item.kind, "name": item.name, "dest": str(dest), "state": state})
    return rows


def install(home: Path, root: Path, targets=TARGETS, copy: bool = False, dry_run: bool = False) -> dict:
    """Install the kit. Returns {'done': [...], 'conflicts': [...]}. Only what this module made is replaced; anything
    else at a destination is a conflict and left untouched."""
    done, conflicts = [], []
    for item, dest, how in _plan(home, root, targets):
        if (dest.exists() or dest.is_symlink()) and not _ours(dest):
            conflicts.append(str(dest))
            continue
        mode = "generate" if how == "generate" else "copy" if copy else "link"
        done.append(f"{mode} {dest}")
        if dry_run:
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.is_symlink() or dest.is_file():
            dest.unlink()
        elif dest.is_dir():
            shutil.rmtree(dest)
        if mode == "generate":
            dest.mkdir()
            (dest / "SKILL.md").write_text(codex_agent_skill(item))
        elif mode == "copy" and item.path.is_dir():
            shutil.copytree(item.path, dest, ignore=shutil.ignore_patterns("__pycache__"))
            (dest / COPY_MARK).write_text(f"copied from {item.path}; reinstall with cad-agent agents install --copy\n")
        elif mode == "copy":
            dest.write_text(item.path.read_text() + f"\n<!-- {COPY_MARK}: copied from {item.path} -->\n")
        else:
            dest.symlink_to(item.path.resolve(), target_is_directory=item.path.is_dir())
    return {"done": done, "conflicts": conflicts}


def worktree_warning(root: Path) -> Optional[str]:
    """A warning when the kit root is a linked git worktree (its .git is a file): it may be removed later."""
    git = root / ".git"
    if git.is_file():
        return (f"{root} is a git worktree; links into it break when it is removed. Prefer the main checkout "
                "(--source) or --copy.")
    return None
