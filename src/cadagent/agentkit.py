"""Install cad-agent's agent workflow kit for Claude Code and Codex (``cad-agent agents``).

The kit lives in the cad-agent checkout: ``skills/<name>/SKILL.md`` (the open agent-skill format both tools read) and
``agents/<name>.md`` (Claude Code subagents: frontmatter ``name``, ``description``, ``tools``, then the prompt).

``install`` puts them where the tools look, for the current user:

- Claude Code: ``~/.claude/skills/<skill>`` and ``~/.claude/agents/<agent>.md``
- Codex: ``~/.codex/skills/<skill>`` (``$CODEX_HOME/skills`` if set); Codex has no subagent files, so each agent is also written as a skill
  ``~/.codex/skills/<agent>/SKILL.md`` (generated, marked, rewritten on every install) to run in a separate session

Skills and agents are symlinked to the checkout by default, so ``git pull`` updates them; ``--copy`` copies instead
(for a checkout that will move). Link to a long-lived checkout, not a feature worktree that will be removed. Only
what this module made is ever replaced (links into a cad-agent checkout, generated files, marked copies); anything else
at a destination, including the user's own links, is reported as a conflict and left alone.
"""
from __future__ import annotations

import os
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional

MARKER = "<!-- generated by `cad-agent agents install` from agents/{name}.md: edit that file, not this one -->"
TARGETS = ("claude", "codex")


@dataclass
class Item:
    kind: str           # 'skill' | 'agent'
    name: str
    path: Path          # skill folder or agent file
    description: str


def kit_root(source: Optional[Path] = None) -> Path:
    """The checkout holding skills/ and agents/: ``source``, else the one this package is installed from (editable)."""
    root = Path(source).expanduser().resolve() if source else Path(__file__).resolve().parents[2]
    if not (root / "skills").is_dir() or not (root / "agents").is_dir():
        raise FileNotFoundError(f"{root} has no skills/ and agents/ folders: install cad-agent from a checkout "
                                "(pip install -e) or pass --source <cad-agent checkout>")
    return root


def _frontmatter(text: str, where: Path) -> Dict[str, str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{where}: no frontmatter (--- name/description ---)")
    import yaml
    try:
        fields = yaml.safe_load(m.group(1))
    except yaml.YAMLError as exc:
        raise ValueError(f"{where}: frontmatter is not valid YAML (quote a description that contains ': '): {exc}") from None
    if not isinstance(fields, dict):
        raise ValueError(f"{where}: frontmatter must be a mapping")
    for line in m.group(1).splitlines():   # in plain YAML " #" starts a comment: the rest of the line would be lost
        key, _, raw = line.partition(":")
        raw = raw.strip()
        if key in ("name", "description") and raw[:1] not in ("'", '"', "|", ">") and " #" in raw:
            raise ValueError(f"{where}: {key} contains ' #', which YAML reads as a comment: quote it")
    for key in ("name", "description"):
        if not isinstance(fields.get(key), str) or not fields[key].strip():
            raise ValueError(f"{where}: frontmatter needs {key}")
    return fields


def items(root: Path) -> List[Item]:
    """Every skill and agent in the kit, checked: names match their folder/file and are unique across both kinds."""
    found = []
    for folder in sorted(p for p in (root / "skills").iterdir() if (p / "SKILL.md").is_file()):
        fm = _frontmatter((folder / "SKILL.md").read_text(), folder / "SKILL.md")
        if fm["name"] != folder.name:
            raise ValueError(f"{folder}/SKILL.md: name {fm['name']!r} does not match its folder")
        found.append(Item("skill", folder.name, folder, fm["description"]))
    for path in sorted((root / "agents").glob("*.md")):
        fm = _frontmatter(path.read_text(), path)
        if fm["name"] != path.stem:
            raise ValueError(f"{path}: name {fm['name']!r} does not match its file name")
        found.append(Item("agent", path.stem, path, fm["description"]))
    names = [i.name for i in found]
    clashes = sorted({n for n in names if names.count(n) > 1})
    if clashes:
        raise ValueError(f"a skill and an agent share a name: {clashes}")
    return found


def codex_agent_skill(item: Item) -> str:
    """An agent as a Codex skill: same name and description, the prompt as the body, run in a separate session."""
    body = re.sub(r"\A---\n.*?\n---\n", "", item.path.read_text(), count=1, flags=re.S).lstrip()
    import yaml
    head = yaml.safe_dump({"name": item.name, "description": item.description}, sort_keys=False, width=1000)
    return (f"---\n{head}---\n\n{MARKER.format(name=item.name)}\n\n"
            "Run this only in its own Codex session, separate from the session that did the work: do not use it on "
            "work you wrote yourself in this session. Whoever starts the session gives the inputs the instructions "
            "below ask for (for example a PR URL and a checkout path).\n\n" + body)


def target_dirs(home: Path) -> Dict[str, Path]:
    """Where each tool looks. Codex honours $CODEX_HOME (default ~/.codex) when installing into your own home."""
    codex = Path(os.environ["CODEX_HOME"]).expanduser() if os.environ.get("CODEX_HOME") and home == Path.home() else home / ".codex"
    return {"claude_skills": home / ".claude/skills", "claude_agents": home / ".claude/agents", "codex_skills": codex / "skills"}


def _check_dirs(dirs: Dict[str, Path], root: Path, targets) -> None:
    """Refuse destinations that resolve into the kit itself, or a Codex skills folder that is the Claude one (the
    generated agent skills would then shadow Claude's own subagents)."""
    kit = [(root / "skills").resolve(), (root / "agents").resolve()]
    for name, folder in dirs.items():
        real = folder.resolve()
        if any(real == k or k in real.parents for k in kit):
            raise ValueError(f"{folder} resolves into the kit itself ({real}); point it somewhere else")
    if "claude" in targets and "codex" in targets and dirs["codex_skills"].resolve() == dirs["claude_skills"].resolve():
        raise ValueError(f"{dirs['codex_skills']} is the same folder as {dirs['claude_skills']}: install with "
                         "--target claude (Codex then sees the skills through it, but not the agents)")


def _plan(home: Path, root: Path, targets) -> List[tuple]:
    """(item, destination, how) for each target: how is 'link' or 'generate'."""
    dirs = target_dirs(home)
    _check_dirs(dirs, root, targets)
    plan = []
    for item in items(root):
        if "claude" in targets:
            if item.kind == "skill":
                plan.append((item, dirs["claude_skills"] / item.name, "link"))
            else:
                plan.append((item, dirs["claude_agents"] / f"{item.name}.md", "link"))
        if "codex" in targets:
            plan.append((item, dirs["codex_skills"] / item.name, "link" if item.kind == "skill" else "generate"))
    return plan


COPY_MARK = ".installed-by-cad-agent"


def _text(path: Path) -> str:
    try:
        return path.read_text()
    except (UnicodeDecodeError, OSError):
        return ""


def _kit_link(dest: Path) -> bool:
    """A link this module made: it points at <kit>/skills/<name> or <kit>/agents/<name>.md of a cad-agent checkout
    (this one or an older one). A dangling link counts if its target path still has that shape inside a folder named
    like a cad-agent checkout (a removed worktree). Links to anything else are the user's."""
    target = Path(os.path.normpath(dest.parent / os.readlink(dest)))
    if target.parent.name not in ("skills", "agents"):
        return False
    kit = target.parent.parent
    if target.exists():
        return (kit / "src/cadagent").is_dir() and (kit / "skills").is_dir() and (kit / "agents").is_dir()
    return "cad-agent" in kit.name


def _ours(dest: Path) -> bool:
    """Something this module put there: a link into a cad-agent kit, a generated Codex agent skill, or a marked copy."""
    if dest.is_symlink():
        return _kit_link(dest)
    if dest.is_dir():
        return (dest / COPY_MARK).is_file() or "generated by `cad-agent agents install`" in _text(dest / "SKILL.md")
    return dest.is_file() and COPY_MARK in _text(dest)


def _copy_current(item: Item, dest: Path) -> bool:
    """A marked copy still matches the kit."""
    if item.path.is_dir():
        sources = {p.relative_to(item.path): p for p in item.path.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
        copies = {p.relative_to(dest): p for p in dest.rglob("*") if p.is_file() and p.name != COPY_MARK}
        return sources.keys() == copies.keys() and all(sources[k].read_bytes() == copies[k].read_bytes() for k in sources)
    return _text(dest).startswith(item.path.read_text())


def status(home: Path, root: Path, targets=TARGETS) -> List[dict]:
    rows = []
    for item, dest, how in _plan(home, root, targets):
        if dest.is_symlink():
            state = "installed" if dest.resolve() == item.path.resolve() else f"links elsewhere ({dest.resolve()})"
        elif not dest.exists():
            state = "missing"
        elif not _ours(dest):
            state = "conflict (not installed by cad-agent)"
        elif how == "generate":
            state = "installed" if _text(dest / "SKILL.md") == codex_agent_skill(item) else "out of date"
        else:
            state = "copied" if _copy_current(item, dest) else "copied, out of date"
        rows.append({"kind": item.kind, "name": item.name, "dest": str(dest), "state": state})
    return rows


def install(home: Path, root: Path, targets=TARGETS, copy: bool = False, dry_run: bool = False) -> dict:
    """Install the kit. Returns {'done': [...], 'conflicts': [...]}. Only what this module made is replaced; anything
    else at a destination is a conflict and left untouched."""
    done, conflicts = [], []
    for item, dest, how in _plan(home, root, targets):
        if (dest.exists() or dest.is_symlink()) and not _ours(dest):
            conflicts.append(str(dest))
            continue
        mode = "generate" if how == "generate" else "copy" if copy else "link"
        done.append(f"{mode} {dest}")
        if dry_run:
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.is_symlink() or dest.is_file():
            dest.unlink()
        elif dest.is_dir():
            shutil.rmtree(dest)
        if mode == "generate":
            dest.mkdir()
            (dest / "SKILL.md").write_text(codex_agent_skill(item))
        elif mode == "copy" and item.path.is_dir():
            shutil.copytree(item.path, dest, ignore=shutil.ignore_patterns("__pycache__"))
            (dest / COPY_MARK).write_text(f"copied from {item.path}; reinstall with cad-agent agents install --copy\n")
        elif mode == "copy":
            dest.write_text(item.path.read_text() + f"\n<!-- {COPY_MARK}: copied from {item.path} -->\n")
        else:
            dest.symlink_to(item.path.resolve(), target_is_directory=item.path.is_dir())
    return {"done": done, "conflicts": conflicts}


def worktree_warning(root: Path) -> Optional[str]:
    """A warning when the kit root is a linked git worktree (its .git is a file): it may be removed later."""
    git = root / ".git"
    if git.is_file():
        return (f"{root} is a git worktree; links into it break when it is removed. Prefer the main checkout "
                "(--source) or --copy.")
    return None
