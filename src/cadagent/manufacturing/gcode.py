"""Read sliced G-code: which bridge and overhang extrusions a slicer warning is about, and where they are.

    from cadagent.manufacturing.gcode import bridge_report
    r = bridge_report('exports/gcode/base.gcode', n=8)
    for e in r['longest']:
        print(e['length_mm'], e['feature'], e['z_mm'], e['start_mm'], e['end_mm'])

A slicer names a stability problem ("Long bridging extrusions", "Floating bridge anchors") without saying where it
is. The slicer labels every extrusion with its feature in G-code comments (PrusaSlicer and OrcaSlicer
``;TYPE:Bridge infill``, Bambu Studio ``; FEATURE: Bridge``), so the longest bridge and overhang-perimeter moves, with
their height and position, point at the feature. Many long bridges are internal: the first solid layer over sparse
infill, which slicer settings fix, not geometry (PrusaSlicer ``solid_infill_below_area``, for one).

Pure Python: no optional dependency. A screen of what the slicer wrote, not a print simulation: a bridge anchored on
both sides prints fine and is listed too, and a long move is not proof that the print sags.
"""
from __future__ import annotations

import io
import math
import re
import zipfile
from pathlib import Path
from typing import Any, Dict, Iterable, Iterator, List, Mapping, Optional, Union

# Slicer feature labels (lower case) -> kind. PrusaSlicer: "Bridge infill", "Overhang perimeter"; Bambu Studio and
# OrcaSlicer: "Bridge", "Internal Bridge", "Overhang wall".
FEATURES: Dict[str, str] = {
    "bridge infill": "bridge",
    "bridge": "bridge",
    "internal bridge": "bridge",
    "overhang perimeter": "overhang",
    "overhang wall": "overhang",
}
# Straight moves of one feature that continue each other within this angle are one extrusion (slicers split a line
# where the speed or flow changes).
MERGE_DEG = 1.0

_FEATURE = re.compile(r"^;\s*(?:TYPE|FEATURE)\s*:\s*(.*?)\s*$", re.IGNORECASE)
_HEIGHT = re.compile(r"^;\s*(?:HEIGHT|LAYER_HEIGHT)\s*:\s*([-+]?[\d.]+)", re.IGNORECASE)
_GENERATED = re.compile(r"^;\s*(?:generated by\s+)?((?:PrusaSlicer|Bambu\s?Studio|OrcaSlicer|SuperSlicer|Slic3r)\b.*)$",
                        re.IGNORECASE)
_WORD = re.compile(r"([A-Z])\s*([-+]?(?:\d+\.?\d*|\.\d+))")
_EPS = 1e-9


def _lines(path: Union[str, Path]) -> Iterator[str]:
    """The G-code lines of a ``.gcode`` file, or of every plate in a sliced Bambu Studio ``.gcode.3mf``/``.3mf``."""
    path = Path(path)
    if zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as z:
            names = sorted(n for n in z.namelist() if n.lower().endswith(".gcode"))
            if not names:
                raise ValueError(f"{path}: a zip with no .gcode inside (slice it first)")
            for name in names:
                with z.open(name) as f:
                    yield from io.TextIOWrapper(f, encoding="utf-8", errors="replace")
        return
    with open(path, encoding="utf-8", errors="replace") as f:
        yield from f


def _arc_length(x0: float, y0: float, x1: float, y1: float, words: Mapping[str, float], clockwise: bool) -> float:
    """Length in XY of a G2 (clockwise) or G3 arc, from its centre offset (I, J) or radius (R); the chord when it has
    neither. Start equal to end with I/J is a full circle."""
    chord = math.hypot(x1 - x0, y1 - y0)
    if "I" in words or "J" in words:
        cx, cy = x0 + words.get("I", 0.0), y0 + words.get("J", 0.0)
        r = math.hypot(x0 - cx, y0 - cy)
        if r < _EPS:
            return chord
        a0, a1 = math.atan2(y0 - cy, x0 - cx), math.atan2(y1 - cy, x1 - cx)
        sweep = (a0 - a1) if clockwise else (a1 - a0)
        sweep %= 2 * math.pi
        if sweep < 1e-9 and chord < 1e-6:
            sweep = 2 * math.pi
        return r * sweep
    if "R" in words:
        r = abs(words["R"])
        if r < _EPS:
            return chord
        sweep = 2 * math.asin(min(1.0, chord / (2 * r)))
        if words["R"] < 0:
            sweep = 2 * math.pi - sweep
        return r * sweep
    return chord


def extrusions(lines: Iterable[str], features: Optional[Mapping[str, str]] = None,
               merge_deg: float = MERGE_DEG) -> Iterator[Dict[str, Any]]:
    """Each extrusion of a feature in ``features`` (label -> kind, default ``FEATURES``), from G-code lines.

    An extrusion is a G0/G1 move, or a run of straight moves of the same feature that continue each other within
    ``merge_deg``, with positive filament in XY, or one G2/G3 arc (its arc length; ``"arc": True``). Absolute and
    relative extrusion (M82/M83, G92 E; absolute until the file says otherwise, as in firmware), absolute and
    relative positions (G90/G91, which leave the extrusion mode alone), inches (G20) and homing (G28) are
    followed. ``z_mm`` is the nozzle height during the move; ``height_mm`` the slicer's ``;HEIGHT:`` or
    ``; LAYER_HEIGHT:`` comment (``None`` if it writes neither); ``line`` the 1-based line of the move's start
    (counted on through the plates of a ``.gcode.3mf``).
    """
    features = {k.lower(): v for k, v in (FEATURES if features is None else features).items()}
    pos = {"X": 0.0, "Y": 0.0, "Z": 0.0}
    e_abs, xyz_abs, e_last, unit = True, True, 0.0, 1.0
    feature: Optional[str] = None
    height: Optional[float] = None
    cos_merge = math.cos(math.radians(merge_deg))
    run: Optional[Dict[str, Any]] = None

    def finish():
        nonlocal run
        out, run = run, None
        if out is not None:
            out.pop("_dir", None)
            out["length_mm"] = round(out["length_mm"], 3)
        return out

    for number, raw in enumerate(lines, 1):
        text = raw.strip()
        if not text:
            continue
        if text.startswith(";"):
            m = _FEATURE.match(text)
            if m:
                feature = m.group(1)
                done = finish()
                if done:
                    yield done
                continue
            m = _HEIGHT.match(text)
            if m:
                try:
                    height = float(m.group(1))
                except ValueError:
                    pass
            continue
        code = text.split(";", 1)[0].upper()
        words_list = _WORD.findall(code)
        if not words_list:
            continue
        cmd = f"{words_list[0][0]}{float(words_list[0][1]):g}"
        words = {k: float(v) for k, v in words_list[1:]}
        if cmd == "M82":
            e_abs = True
        elif cmd == "M83":
            e_abs = False
        elif cmd == "G90":                  # positions only: slicers set the extrusion mode with M82/M83, and
            xyz_abs = True                   # custom blocks wrap moves in G91 ... G90 inside an M83 print
        elif cmd == "G91":
            xyz_abs = False
        elif cmd == "G20":
            unit = 25.4
        elif cmd == "G21":
            unit = 1.0
        elif cmd == "G92":
            if "E" in words:
                e_last = words["E"] * unit
            for a in "XYZ":
                if a in words:
                    pos[a] = words[a] * unit
        elif cmd == "G28":
            for a in [a for a in "XYZ" if a in code[3:]] or "XYZ":
                pos[a] = 0.0
        elif cmd in ("G0", "G1", "G2", "G3"):
            x0, y0 = pos["X"], pos["Y"]
            for a in "XYZ":
                if a in words:
                    pos[a] = words[a] * unit if xyz_abs else pos[a] + words[a] * unit
            de = 0.0
            if "E" in words:
                e = words["E"] * unit
                de = e - e_last if e_abs else e
                e_last = e if e_abs else e_last + e
            x1, y1 = pos["X"], pos["Y"]
            moved = math.hypot(x1 - x0, y1 - y0) > _EPS or (cmd in ("G2", "G3") and ("I" in words or "J" in words))
            kind = features.get((feature or "").lower())
            if de <= _EPS or not moved or kind is None:
                if moved or de < -_EPS:                     # a travel or a retraction ends the extrusion
                    done = finish()
                    if done:
                        yield done
                continue
            arc = cmd in ("G2", "G3")
            length = _arc_length(x0, y0, x1, y1, words, cmd == "G2") if arc else math.hypot(x1 - x0, y1 - y0)
            d = None if arc else ((x1 - x0) / length, (y1 - y0) / length)
            if (run is not None and d is not None and run["_dir"] is not None and run["feature"] == feature
                    and abs(run["z_mm"] - round(pos["Z"], 3)) < 1e-6
                    and d[0] * run["_dir"][0] + d[1] * run["_dir"][1] >= cos_merge):
                run["length_mm"] += length
                run["end_mm"] = [round(x1, 3), round(y1, 3)]
                run["moves"] += 1
                continue
            done = finish()
            if done:
                yield done
            run = {"length_mm": length, "feature": feature, "kind": kind, "z_mm": round(pos["Z"], 3),
                   "height_mm": height, "start_mm": [round(x0, 3), round(y0, 3)], "end_mm": [round(x1, 3), round(y1, 3)],
                   "line": number, "moves": 1, "arc": arc, "_dir": d}
            if arc:
                done = finish()
                if done:
                    yield done
    done = finish()
    if done:
        yield done


class _Header:
    """Passes lines through, noting the slicer's name and whether any extrusion carries a feature label."""

    def __init__(self, lines: Iterable[str]):
        self.lines, self.slicer, self.labelled = lines, None, False

    def __iter__(self) -> Iterator[str]:
        for i, line in enumerate(self.lines):
            if line.lstrip().startswith(";"):
                text = line.strip()
                if self.slicer is None and i < 50:
                    m = _GENERATED.match(text)
                    if m:
                        self.slicer = m.group(1).strip()
                if not self.labelled and _FEATURE.match(text):
                    self.labelled = True
            yield line


def bridge_report(path: Union[str, Path], n: int = 10, features: Optional[Mapping[str, str]] = None,
                  merge_deg: float = MERGE_DEG) -> Dict[str, Any]:
    """The ``n`` longest bridge and overhang-perimeter extrusions in a sliced G-code file, and a summary per feature.

    ``path`` is a ``.gcode`` file (PrusaSlicer, Bambu Studio, OrcaSlicer) or a sliced Bambu Studio ``.gcode.3mf``
    (every plate's G-code). ``features`` maps slicer feature labels (case-insensitive) to a kind, ``"bridge"`` or
    ``"overhang"``; the default is ``FEATURES``. Each listed extrusion is as ``extrusions`` yields it: ``length_mm``,
    ``feature``, ``kind``, ``z_mm``, ``height_mm``, ``start_mm``, ``end_mm`` (XY), ``line``, ``moves``, ``arc``.

    A screen of the slicer's own labels: it does not know whether a bridge is anchored on both sides (most are), and
    a file with no labels lists nothing (``"labelled": False``).
    """
    if n < 0:
        raise ValueError(f"n must be 0 or more, not {n}")
    lines = _Header(_lines(path))
    found = list(extrusions(lines, features, merge_deg))
    summary: Dict[str, Dict[str, Any]] = {}
    for e in found:
        s = summary.setdefault(e["feature"], {"kind": e["kind"], "extrusions": 0, "total_mm": 0.0, "longest_mm": 0.0,
                                              "z_mm": [e["z_mm"], e["z_mm"]]})
        s["extrusions"] += 1
        s["total_mm"] += e["length_mm"]
        s["longest_mm"] = max(s["longest_mm"], e["length_mm"])
        s["z_mm"] = [min(s["z_mm"][0], e["z_mm"]), max(s["z_mm"][1], e["z_mm"])]
    for s in summary.values():
        s["total_mm"] = round(s["total_mm"], 3)
    longest = sorted(found, key=lambda e: (-e["length_mm"], e["line"]))[:n]
    return {"file": str(path), "slicer": lines.slicer, "labelled": lines.labelled, "features": summary, "longest": longest}
