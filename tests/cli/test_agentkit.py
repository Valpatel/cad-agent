import re

import pytest
import yaml

from cadagent import agentkit
from cadagent.cli import main


def kit(tmp_path):
    root = tmp_path / 'cad-agent-kit'
    (root / 'src/cadagent').mkdir(parents=True)
    (root / 'skills/alpha').mkdir(parents=True)
    (root / 'skills/alpha/SKILL.md').write_text('---\nname: alpha\ndescription: "Use when: alpha things"\n---\n\nBody A\n')
    (root / 'agents').mkdir()
    (root / 'agents/reviewer.md').write_text('---\nname: reviewer\ndescription: Reviews a PR\ntools: Bash, Read\n---\n\nYou review.\n')
    return root


def test_real_kit_is_valid():
    root = agentkit.kit_root()
    found = {(i.kind, i.name) for i in agentkit.items(root)}
    assert {('skill', 'cad-work-tracking'), ('skill', 'cad-pr-review'), ('skill', 'cad-remote-runs'),
            ('agent', 'cad-pr-reviewer'), ('agent', 'cad-resume')} <= found
    for item in agentkit.items(root):
        if item.kind == 'agent':      # the generated Codex skill parses and keeps the description
            text = agentkit.codex_agent_skill(item)
            fm = yaml.safe_load(re.match(r'---\n(.*?)\n---\n', text, re.S).group(1))
            assert fm == {'name': item.name, 'description': item.description}


def test_install_links_and_generates_then_reinstalls(tmp_path):
    root, home = kit(tmp_path), tmp_path / 'home'
    r = agentkit.install(home, root)
    assert not r['conflicts'] and len(r['done']) == 4
    assert (home / '.claude/skills/alpha').resolve() == (root / 'skills/alpha').resolve()
    assert (home / '.claude/agents/reviewer.md').resolve() == (root / 'agents/reviewer.md').resolve()
    assert (home / '.agents/skills/alpha').is_symlink()
    codex_agent = (home / '.agents/skills/reviewer/SKILL.md').read_text()
    assert 'generated by `cad-agent agents install`' in codex_agent and 'You review.' in codex_agent
    assert {row['state'] for row in agentkit.status(home, root)} == {'installed'}
    (root / 'agents/reviewer.md').write_text((root / 'agents/reviewer.md').read_text() + 'More.\n')
    assert 'out of date' in {row['state'] for row in agentkit.status(home, root)}
    assert not agentkit.install(home, root)['conflicts']          # links and generated files are replaced
    assert 'More.' in (home / '.agents/skills/reviewer/SKILL.md').read_text()


def test_foreign_files_are_conflicts_and_left_alone(tmp_path):
    root, home = kit(tmp_path), tmp_path / 'home'
