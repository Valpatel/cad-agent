def test_checks_are_local(monkeypatch):
    calls = []
    monkeypatch.setattr(agentkit.shutil, 'which', lambda name: None)
    assert 'not on PATH' in agentkit._gh_logged_in() and 'not on PATH' in agentkit.REQUIREMENTS['git'].check()
    monkeypatch.setattr(agentkit.shutil, 'which', lambda name: f'/usr/bin/{name}')

    class Done:
        def __init__(self, code):
            self.returncode = code

    def run(cmd, **kw):
        calls.append(cmd)
        assert kw.get('stdout') is agentkit.subprocess.DEVNULL       # the token is never read into this process
        return Done(1)
    monkeypatch.setattr(agentkit.subprocess, 'run', run)
    assert agentkit._gh_logged_in() == '`gh` is not logged in: run `gh auth login`'
    assert calls == [['gh', 'auth', 'token']]                          # reads gh's own config: no network call
    monkeypatch.setattr(agentkit.importlib.util, 'find_spec', lambda name: None)
    assert 'Playwright is not installed' in agentkit._playwright()


def test_the_workflow_page_lists_who_needs_what():
    """docs/practice/agent-workflow.md's table of needs names, for each need, exactly the items whose frontmatter has it."""
    root = agentkit.kit_root()
    page = (root / 'docs/practice/agent-workflow.md').read_text()
    rows = {}
    for line in page.splitlines():
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) == 3 and cells[0] in {r.label for r in agentkit.REQUIREMENTS.values()}:
            rows[cells[0]] = set(re.findall(r'`([a-z0-9-]+)`', cells[2]))
    used = {}
    for item in agentkit.items(root):
        for r in item.requires + item.optional:
            used.setdefault(agentkit.REQUIREMENTS[r].label, set()).add(item.name)
    assert rows == used


def test_old_codex_links_move_to_the_shared_folder_and_only_ours_go(tmp_path):
    root, home = kit(tmp_path), tmp_path / 'home'
    old = home / '.codex/skills'
    old.mkdir(parents=True)
    (old / 'alpha').symlink_to(root / 'skills/alpha')                     # an earlier install's link
    (old / 'reviewer').mkdir()
    (old / 'reviewer/SKILL.md').write_text(agentkit.codex_agent_skill(agentkit.items(root)[1]))
    (old / 'mine').mkdir()                                                # the person's own skill stays
    (old / 'mine/SKILL.md').write_text('---\nname: mine\ndescription: Mine\n---\n')
    r = agentkit.install(home, root)
    assert sorted(p.name for p in old.iterdir()) == ['mine']
    assert len(r['removed']) == 2 and (home / '.agents/skills/alpha').is_symlink()
    assert agentkit.install(home, root, targets=('codex',))['removed'] == []      # codex is the shared folder now


def test_prune_removes_what_the_kit_dropped_and_uninstall_removes_everything(tmp_path):
    root, home = kit(tmp_path), tmp_path / 'home'
    (root / 'skills/beta').mkdir()
    (root / 'skills/beta/SKILL.md').write_text('---\nname: beta\ndescription: Beta\n---\n\nB\n')
    agentkit.install(home, root)
    import shutil
    shutil.rmtree(root / 'skills/beta')                                   # the kit drops a skill
    r = agentkit.install(home, root)
    assert sorted(r['removed']) == sorted(f'remove {home / d / "beta"} (no longer in the kit)'
                                          for d in ('.claude/skills', '.agents/skills'))
    assert not (home / '.claude/skills/beta').is_symlink()
    (home / '.claude/skills/own').mkdir()                                 # not ours: uninstall leaves it
    gone = agentkit.uninstall(home)
    assert len(gone) == 4 and [p.name for p in (home / '.claude/skills').iterdir()] == ['own']
    assert not any((home / '.agents/skills').iterdir())


