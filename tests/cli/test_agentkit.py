def kit(tmp_path):
    root = tmp_path / 'cad-agent-kit'
    (root / 'software/cadagent').mkdir(parents=True)
    (root / '.agents/skills/alpha').mkdir(parents=True)
    (root / '.agents/skills/alpha/SKILL.md').write_text('---\nname: alpha\ndescription: "Use when: alpha things"\n---\n\nBody A\n')
    (root / '.agents/agents').mkdir(parents=True)
    (root / '.agents/agents/reviewer.md').write_text('---\nname: reviewer\ndescription: Reviews a PR\ntools: Bash, Read\n---\n\nYou review.\n')
    return root


def test_real_kit_is_valid():
    root = agentkit.kit_root()
    found = {(i.kind, i.name) for i in agentkit.items(root)}
    assert found == {('skill', name) for name in ('cad-motion-validation', 'cad-pr-review', 'cad-remote-runs',
                     'cad-supply-chain', 'cad-work-tracking', 'design-process', 'mcmaster-parts', 'pem-fastener-selection', 'sheet-metal-hardware',
                     'scada-component-authoring', 'scada-system-authoring', 'scada-model-adaptation',
                     'scada-viewer-review', 'scada-distribution-review', 'repository-documentation')} | \
                    {('agent', 'cad-pr-reviewer'), ('agent', 'cad-resume')}
    for item in agentkit.items(root):
        if item.kind == 'agent':      # the generated Codex skill parses and keeps the description
            text = agentkit.codex_agent_skill(item)
            fm = yaml.safe_load(re.match(r'---\n(.*?)\n---\n', text, re.S).group(1))
            assert fm == {'name': item.name, 'description': item.description}


