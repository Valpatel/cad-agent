"""tools/archive_pointers.py (#789, #323): offline-mirror `archive` pointers from a JSONL manifest, on a small synthetic
registry (a hand-formatted core file with comments and one importer-layout shard). Offline."""
import difflib
import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("archive_pointers", ROOT / "tools" / "archive_pointers.py")
ap = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ap)
ir, ha, refs = ap.ir, ap.ha, ap.refs

SHA_A, SHA_B, SHA_C, SHA_D = ("a" * 64), ("b" * 64), ("c" * 64), ("d" * 64)
CORE = """# A synthetic core registry: comments and layout must survive.
schema: 1
updated: 2026-11-01

sources:
  # ---- one group
  - id: core-plain
    title: A plain source
    url: https://example.org/plain.pdf
    areas:
    - testing
    verified: '2026-11-01: read pages 1-2, a long note that wraps
      onto a second line'
    summary: One sentence.
    used_for:
    - docs/example.md

  - id: core-archived
    title: Already mirrored
    url: https://example.org/kept.html
    verified: '2026-11-02: read it'
    archive:
      sha256: %s
      kind: html
      fetched: '2026-11-02'
      redistribute: false
  - id: core-untouched
    title: Not in the manifest
    url: https://example.org/other
    verified: '2026-11-03: read it'

# ---- not sources
unverified:
  - id: core-unverified
    url: https://example.org/plain.pdf
    why: not read
""" % SHA_C
SHARD_RECORDS = [
    {"id": "shard-frag", "kind": "guide", "title": "Fragment url", "url": "https://example.org/guide#section-2",
     "summary": "S.", "used_for": [], "imported": "0123456789abcdef"},
    {"id": "shard-end", "kind": "guide", "title": "No summary", "url": "https://example.org/end", "used_for": []},
    {"id": "shard-mismatch", "kind": "guide", "title": "Different bytes", "url": "https://example.org/changed",
     "verified": "2026-11-04: read", "archive": {"sha256": SHA_C, "kind": "pdf", "fetched": "2026-11-04",
                                                   "redistribute": False}},
    {"id": "shard-ext", "extends": True, "summary": "an extension has no url"},
]
SHARD = "docs/research/references/guides-test.yaml"


@pytest.fixture
def root(tmp_path):
    (tmp_path / "docs/research/references").mkdir(parents=True)
    (tmp_path / ap.CORE).write_text(CORE)
    head = "# Generated by a test.\n"
    (tmp_path / SHARD).write_text(head + ir.dump({"schema": 2, "title": "Test", "sources": SHARD_RECORDS}))
    (tmp_path / "docs/research/references/vocab.yaml").write_text("kind: [guide]\n")
    return tmp_path


def manifest(tmp_path, *lines):
    path = tmp_path / "manifest.jsonl"
    path.write_text("\n".join(x if isinstance(x, str) else json.dumps(x) for x in lines) + "\n")
    return path


def entry(url, sha, fetched="2026-11-14", kind="pdf"):
    return {"url": url, "sha256": sha, "fetched": fetched, "kind": kind}


GOOD = (entry("https://example.org/plain.pdf", SHA_A), entry("https://example.org/kept.html", SHA_C, kind="html"),
        entry("https://example.org/guide", SHA_B, kind="html"), entry("https://example.org/end", SHA_D, kind="html"),
        entry("https://example.org/changed", SHA_A))


def run(root, path, *extra):
    return ap.main(["--manifest", str(path), "--root", str(root), *extra])


def load(root, rel):
    return refs._yaml(ha.split_head((root / rel).read_text())[1])


def test_a_dry_run_counts_per_file_and_writes_nothing(root, tmp_path, capsys):
    before = {p: (root / p).read_text() for p in (ap.CORE, SHARD)}
    assert run(root, manifest(tmp_path, *GOOD)) == 0
    out = capsys.readouterr().out
    assert f"{ap.CORE}: 1 added, 1 already archived, 0 mismatched" in out
    assert f"{SHARD}: 2 added, 0 already archived, 1 mismatched" in out
    assert "3 pointer(s) in 2 file(s)" in out and "dry run" in out
    assert {p: (root / p).read_text() for p in before} == before


def test_a_write_adds_pointers_where_the_existing_ones_sit_and_keeps_the_layout(root, tmp_path):
    old_core = (root / ap.CORE).read_text()
    assert run(root, manifest(tmp_path, *GOOD), "--write") == 0
    core = (root / ap.CORE).read_text()
    # the core file: only the five pointer lines are new, after the later of verified/summary; comments kept
    diff = list(difflib.ndiff(old_core.splitlines(), core.splitlines()))
    assert not [ln for ln in diff if ln.startswith("- ")]
    added = [ln[2:] for ln in diff if ln.startswith("+ ")]
    assert added == ["    archive:", f"      sha256: {SHA_A}", "      kind: pdf", "      fetched: '2026-11-14'",
                     "      redistribute: false"]
    assert "    summary: One sentence.\n    archive:\n" in core and "# ---- one group" in core
    doc = refs._yaml(core)
    plain = doc["sources"][0]
    assert list(plain) == ["id", "title", "url", "areas", "verified", "summary", "archive", "used_for"]
    assert plain["archive"] == {"sha256": SHA_A, "kind": "pdf", "fetched": "2026-11-14", "redistribute": False}
    assert "archive" not in doc["unverified"][0]          # only `sources` gains pointers
    # the shard: the exact parse/dump round-trip the weekly health updater needs still holds
    text = (root / SHARD).read_text()
    assert ha.editable(text)
    frag, end, mismatch, ext = load(root, SHARD)["sources"]
    assert list(frag)[list(frag).index("summary") + 1] == "archive" and frag["archive"]["sha256"] == SHA_B
    assert list(end)[-1] == "archive" and end["archive"]["kind"] == "html"
    assert mismatch["archive"]["sha256"] == SHA_C          # never overwritten
    assert "archive" not in ext


def test_a_second_run_changes_nothing(root, tmp_path, capsys):
    path = manifest(tmp_path, *GOOD)
    run(root, path, "--write")
    after = {p: (root / p).read_text() for p in (ap.CORE, SHARD)}
    capsys.readouterr()
    run(root, path, "--write")
    assert "0 pointer(s) in 0 file(s); 4 already archived, 1 mismatched" in capsys.readouterr().out
    assert {p: (root / p).read_text() for p in after} == after


def test_a_sha_mismatch_is_reported_and_not_overwritten(root, tmp_path, capsys):
    run(root, manifest(tmp_path, entry("https://example.org/changed", SHA_A)), "--write")
    out = capsys.readouterr().out
    assert f"mismatch {SHARD} shard-mismatch: the registry has {SHA_C}, the manifest {SHA_A}" in out
    assert load(root, SHARD)["sources"][2]["archive"]["sha256"] == SHA_C


def test_an_archived_record_with_the_same_sha_is_left_alone(root, tmp_path, capsys):
    before = (root / ap.CORE).read_text()
    run(root, manifest(tmp_path, entry("https://example.org/kept.html", SHA_C, "2026-11-15", "html")), "--write")
    assert f"{ap.CORE}: 0 added, 1 already archived" in capsys.readouterr().out
    assert (root / ap.CORE).read_text() == before


@pytest.mark.parametrize("bad", [
    "not json", "[1, 2]", json.dumps({"url": "https://example.org/end"}),
    json.dumps(entry("ftp://example.org/end", SHA_A)), json.dumps(entry("https://example.org/end", "A" * 64)),
    json.dumps(entry("https://example.org/end", "a" * 63)), json.dumps(entry("https://example.org/end", SHA_A, "2026-13-01")),
    json.dumps(entry("https://example.org/end", SHA_A, "2026-W46-1")),
    json.dumps(entry("https://example.org/end", SHA_A, "14 Nov 2026")), json.dumps(entry("https://example.org/end", SHA_A, kind="PDF")),
    json.dumps(entry("https://example.org/end", SHA_A, kind="yes")), json.dumps(entry("https://ex ample.org/end", SHA_A)),
])
def test_malformed_lines_are_counted_and_skipped(root, tmp_path, bad):
    by_url, counts = ap.read_manifest(manifest(tmp_path, bad, "", entry("https://example.org/plain.pdf", SHA_A)))
    assert counts["lines"] == 2 and counts["malformed"] == 1
    assert list(by_url) == ["https://example.org/plain.pdf"]


def test_the_latest_fetch_wins_and_a_same_day_conflict_is_dropped(tmp_path):
    by_url, counts = ap.read_manifest(manifest(
        tmp_path, entry("https://example.org/a", SHA_A, "2026-11-01"), entry("https://example.org/a", SHA_B, "2026-11-05"),
        entry("https://example.org/b", SHA_A), entry("https://example.org/b", SHA_B)))
    assert by_url["https://example.org/a"]["sha256"] == SHA_B
    assert "https://example.org/b" not in by_url and counts["conflicting"] == ["https://example.org/b"]


def test_a_shard_out_of_the_importer_layout_is_left_alone(root, tmp_path, capsys):
    text = (root / SHARD).read_text().replace("title: Test", "title: 'Test'")
    (root / SHARD).write_text(text)
    run(root, manifest(tmp_path, *GOOD), "--write")
    assert "not in the importer's layout" in capsys.readouterr().out
    assert (root / SHARD).read_text() == text


def test_the_tool_names_no_path_or_host_in_what_it_writes(root, tmp_path):
    run(root, manifest(tmp_path, *GOOD), "--write")
    for rel in (ap.CORE, SHARD):
        text = (root / rel).read_text()
        assert str(tmp_path) not in text and "manifest.jsonl" not in text

@pytest.mark.parametrize("summary", ["summary: |\n      First paragraph.\n\n      Second paragraph.\n",
                                     "summary: Last line without a newline."])
def test_unparseable_candidate_preserves_core_and_updates_independent_shards(root, tmp_path, capsys, summary):
    core = root / ap.CORE
    before = ("sources:\n  - id: tricky\n    url: https://example.org/plain.pdf\n    " + summary).encode()
    core.write_bytes(before)
    assert run(root, manifest(tmp_path, *GOOD), "--write") == 0
    report = capsys.readouterr().out
    assert f"{ap.CORE}: left alone" in report
    assert core.read_bytes() == before
    assert load(root, SHARD)["sources"][0]["archive"]["sha256"] == SHA_B


def test_valid_yaml_with_wrong_inserted_value_preserves_core(root, tmp_path, monkeypatch, capsys):
    core = root / ap.CORE
    before = core.read_bytes()
    original_dump = ir.dump
    monkeypatch.setattr(ir, "dump", lambda data: original_dump(data).replace(SHA_A, SHA_B))
    run(root, manifest(tmp_path, entry("https://example.org/plain.pdf", SHA_A)), "--write")
    assert "would change more than the pointers" in capsys.readouterr().out
    assert core.read_bytes() == before


def test_shared_digests_report_only_distinct_usable_urls_in_stable_order(root, tmp_path, capsys):
    path = manifest(tmp_path, entry("https://example.org/b", SHA_A), entry("https://example.org/a", SHA_A),
                    entry("https://example.org/b", SHA_A), entry("https://example.org/conflict", SHA_A),
                    entry("https://example.org/conflict", SHA_B), entry("https://example.org/updated", SHA_A),
                    entry("https://example.org/updated", SHA_C, "2026-11-15"))
    run(root, path)
    lines = [line for line in capsys.readouterr().out.splitlines() if line.startswith("shared sha256 ")]
    assert lines == [f"shared sha256 {SHA_A}: https://example.org/a, https://example.org/b"]
