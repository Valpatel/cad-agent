/** kit/model/model.js, the <cad-model> element's decoder, against the reference (cadagent.publish.view.unpack_model): the packed
 * fixture decodes to what Python decodes, and the site's committed Gyropup model decodes whole and in place (#179). */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import { decodeModel, inflate, partLabel, planMeshHashes } from '../../software/cadagent/webkit/model/model.js';

const root = path.resolve(import.meta.dirname, '../..');
const load = async (json) => {
  const model = JSON.parse(await readFile(path.join(root, json), 'utf8'));
  const packed = await readFile(path.join(path.dirname(path.join(root, json)), model.bin));
  return { model, packed, parts: decodeModel(model, await inflate(packed)) };
};

test('decodeModel reads the fixture exactly as unpack_model does', async () => {
  const { parts } = await load('tests/fixtures/model/two-parts.json');
  const want = JSON.parse(await readFile(path.join(root, 'tests/fixtures/model/two-parts.decoded.json'), 'utf8'));
  assert.equal(parts.length, want.length);
  for (const [i, part] of parts.entries()) {
    assert.deepEqual([...part.index], want[i].triangles.flat(), `${want[i].name}: triangles`);
    const got = [...part.positions], flat = want[i].vertices.flat();
    assert.equal(got.length, flat.length);
    // float32 in the browser against float64 in numpy: well under the 0.0008 mm quantisation step here
    for (let k = 0; k < got.length; k++) assert.ok(Math.abs(got[k] - flat[k]) < 1e-4, `${want[i].name}[${k}]: ${got[k]} vs ${flat[k]}`);
  }
});

test('the site\'s Gyropup model decodes whole, matches its checksum and sits where its parts were exported', async () => {
  const { model, packed, parts } = await load('tools/site/assets/models/gyropup.json');
  assert.equal(model.schema, 'cad-agent-model/1');
  assert.equal(packed.length, model.bytes);
  assert.equal(createHash('sha256').update(packed).digest('hex'), model.sha256);
  assert.ok(model.bytes < 400 * 1024, `the home page's model stays small: ${model.bytes} bytes`);
  assert.equal(parts.reduce((n, p) => n + p.index.length / 3, 0), model.triangles);
  const hash = bytes => createHash('sha256').update(bytes).digest('hex');
  const source = model.source;
  assert.match(source.revision, /^[0-9a-f]{40}$/);
  assert.match(source.hardware_tree, /^[0-9a-f]{40}$/);
  assert.equal(source.files[source.collector], source.collector_sha256, 'the collector is in the recorded source closure');
  assert.equal(source.producer_sha256, hash(await readFile(path.join(root, 'tools/gyropup_showcase.py'))), 'model was generated by the current producer');
  const visible = model.parts.map(p => p.name).sort();
  assert.deepEqual(Object.keys(source.members).filter(n => !source.left_out.includes(n)).sort(), visible, 'every collected group is visible or explicitly omitted');
  const members = Object.values(source.members).flat();
  assert.equal(new Set(members).size, members.length, 'each source part has one recorded group');
  assert.ok(Object.values(source.members).every(names => names.length > 0));
  // This source-bound homepage fixture must show the accepted front/rear packs, not the former belly enclosure.
  assert.equal(source.revision, '3a40891962b0b0a04625e070700f1d130bea3c7b', 'the end-pack fixture records its actual source');
  assert.equal(parts.length, 32, 'the accepted model has 32 visible groups');
  assert.equal(members.length, 224, 'the accepted source has 224 unique parts');
  for (const name of ['end_pack_holder_front', 'end_pack_holder_rear', 'end_foot_front', 'end_foot_rear'])
    assert.ok(members.includes(name), `${name}: current end-pack support is present`);
  for (const name of ['adapter_plate_front', 'adapter_plate_rear', 'bay_door_front', 'bay_door_rear', 'bay_floor',
    'bay_rail_l', 'bay_rail_r', 'bay_side_l', 'bay_side_r', 'bay_skid_1', 'bay_skid_2', 'bay_skid_3', 'bay_skid_4'])
    assert.ok(!members.includes(name), `${name}: retired belly enclosure is absent`);
  assert.deepEqual(source.members.battery.slice().sort(), ['item.battery_front', 'item.battery_rear']);
  const battery = model.parts.find(p => p.name === 'battery');
  const acceptedBattery = [-286.775, -48.5, -87.04, 286.775, 48.5, 49.96];
  assert.ok(battery && battery.bounds_mm.every((v, k) => Math.abs(v - acceptedBattery[k]) < 0.02),
    'battery placement matches the accepted front/rear packs, not the old belly');
  const { banner } = JSON.parse(await readFile(path.join(root, 'docs/img/gyropup/SOURCE.json'), 'utf8'));
  assert.equal(banner.revision, source.revision, 'project card and interactive model describe one source');
  for (const [file, sha] of [['tools/site/assets/models/gyropup.json', banner.model_sha256],
    [banner.poster, banner.poster_sha256], [banner.file, banner.sha256]])
    assert.equal(hash(await readFile(path.join(root, file))), sha, `${file} belongs to the recorded model/poster set`);
  assert.equal(banner.binary_sha256, model.sha256);
  for (const [i, part] of parts.entries()) {
    const meta = model.parts[i], n = part.positions.length / 3;
    assert.equal(n, meta.vertices, meta.name);
    assert.ok(part.index.every(v => v < n), `${meta.name}: an index past its vertices`);
    const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
    for (let k = 0; k < part.positions.length; k++) { lo[k % 3] = Math.min(lo[k % 3], part.positions[k]); hi[k % 3] = Math.max(hi[k % 3], part.positions[k]); }
    // Inside the box measured on the current CAD solid (to 0.02 mm: rounding and one 16-bit step) and filling it
    // to within 1 mm (that box is OpenCascade's, a little loose on curved faces, and a 0.3 mm chord cuts inside them).
    [...lo, ...hi].forEach((v, k) => {
      const inward = k < 3 ? v - meta.bounds_mm[k] : meta.bounds_mm[k] - v;
      assert.ok(inward > -0.02 && inward < 1, `${meta.name}: bound ${k} is ${v.toFixed(3)}, exported ${meta.bounds_mm[k]}`);
    });
  }
});

