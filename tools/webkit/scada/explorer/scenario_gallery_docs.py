"""Generated navigation maps for the model-owned scenario image gallery.

This module changes documentation only. Capture provenance is checked by the
owning generator before these maps can be refreshed without new screenshots.
"""
import html
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from gallery_maps import folder_map_svg


def gallery_index(manifest):
    def safe(value):
        return html.escape(str(value), quote=True).replace('|', '&#124;')
    sectors = sorted({entry['sector'] for entry in manifest['scenarios']})
    lines = ['# Simulation scenario gallery', '',
             f"**{len(manifest['scenarios'])} illustrative systems** grouped by sector. These previews belong to the simulation library and travel with its system/model examples.", '',
             'Each image shows the real viewer after resetting the model, pausing the host clock and using Zoom to fit. Diagram layout is illustrative; overview text size depends on the system bounds. Open the portable Explorer example to zoom, inspect equipment and issue commands.', '',
             '[Package owner](../README.md) · [Compact SVG topology maps](topologies/README.md) · [Thumbnail folder map](thumbnails/README.md) · [Explorer instructions](../../explorer/README.md) · [Contact sheet](thumbnails/contact-sheet.jpg) · [Capture manifest](../metadata/thumbnails.json)', '',
             'The UI library owns its separate [symbol and workspace gallery](../../ui/img/README.md). Each library keeps its own image directory; there is no shared root asset bucket.', '',
             '![Simulation image folder map](thumbnails/gallery-map.svg)', '',
             '| Folder or file | Purpose |', '| --- | --- |', '| [topologies/](topologies/README.md) | Compact static vector process maps with equipment symbols and declared directed connections. |', '| [thumbnails/](thumbnails/README.md) | One real initial-view JPEG per scenario, plus the complete contact sheet. |', '| [Capture manifest](../metadata/thumbnails.json) | Source hashes, captured view, camera coverage and image dimensions. |', '',
             'The SCADA development tools own capture tooling; this model package owns the resulting images. Regenerate captures only when rendering or model inputs change. Documentation-only map refreshes use `npm --prefix tools/webkit/scada run thumbnails:scenarios -- --indexes-only` after the existing capture provenance and bytes pass validation.', '']
    for sector in sectors:
        lines += ['## ' + safe(sector), '', '| Preview | System | Definitions and example |', '| --- | --- | --- |']
        for entry in manifest['scenarios']:
            if entry['sector'] != sector:
                continue
            image = entry['path'].removeprefix('img/')
            title = safe(entry['title'])
            lines.append(f'| <a href="{image}"><img src="{image}" alt="{title} initial diagram" width="300"></a> | **{title}**<br>`{safe(entry["id"])}` | [System JSON](../scenarios/{entry["system"]}) · [Model JSON](../scenarios/{entry["model"]}) · [Portable example](../../explorer/index.html?scenario={entry["id"]}) |')
        lines += ['']
    lines += ['Generated by the Explorer capture tool with `npm --prefix tools/webkit/scada run thumbnails:scenarios`. Check freshness with `npm --prefix tools/webkit/scada run thumbnails:scenarios -- --check`. Do not hand-edit the images, index or capture manifest.', '']
    return '\n'.join(lines)



def thumbnail_index(manifest):
    return asset_gallery_maps(manifest['scenarios'], 'thumbnails')['img/thumbnails/README.md']


def asset_gallery_maps(records, kind):
    """One gallery map per level; each preview travels with its scenario folder."""
    from posixpath import dirname, relpath
    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from scada_paths import scenario_sector_groups, scenario_asset_path
    if kind not in {'thumbnails', 'topologies'}:
        raise ValueError('Unknown scenario gallery kind')
    groups = scenario_sector_groups(records)
    base = f'img/{kind}'
    captured = kind == 'thumbnails'
    heading = 'Captured simulation views' if captured else 'Compact topology diagrams'
    explanation = ('Real Explorer images captured after reset, pause and Zoom to fit. Values and behavior remain illustrative; overview text size is not an operating-scale readability guarantee.' if captured else 'Static SVG schematics of a declared view, selected by the catalog topologyView when present. Symbols identify equipment; arrows show declared connections, not instantaneous flow or measured facility performance.')
    manifest = 'metadata/' + ('thumbnails.json' if captured else 'topologies.json')
    maps = {base + '/gallery-map.svg': folder_map_svg('scada/sim/' + base + '/', [('sector / scenario /', 'Stable system identity'), ('preview.jpg' if captured else 'topology.svg', 'Fitted initial view' if captured else 'Declared equipment and links'), ('README.md', 'Definitions and companion view')], 'Each sector contains a folder per scenario, with its preview and links to system definitions.')}

    def safe(value):
        return html.escape(str(value), quote=True).replace('|', '&#124;')

    def link(label, target, current):
        return f'[{label}]({relpath(target, dirname(current))})'

    def picture(entry, current, width):
        image = relpath(entry['path'], dirname(current))
        return f'<a href="{image}"><img src="{image}" width="{width}" alt="{safe(entry["title"])} {"initial captured view" if captured else "declared topology"}"></a>'

    root = base + '/README.md'
    lines = [f'# {heading}', '', explanation, '',
             link('Library image gallery', 'img/README.md', root) + ' · ' + link('Scenario definitions', 'scenarios/README.md', root) + ' · ' + link('Generation metadata', manifest, root), '',
             '![Scenario image folder map](gallery-map.svg)', '',
             '| Map | Purpose |', '| --- | --- |', '| [gallery-map.svg](gallery-map.svg) | Shared sector, scenario and image ownership map. |', '',
             f'Browse {len(records)} scenarios in {len(groups)} sectors. Paths use `sector/scenario/preview.jpg` for captures and `sector/scenario/topology.svg` for topology maps.', '',
             '| Sector | Scenarios | Representative preview |', '| --- | ---: | --- |']
    for slug, label, entries in groups:
        sector_map = f'{base}/{slug}/README.md'
        lines.append(f'| {link(safe(label), sector_map, root)} | {len(entries)} | {picture(entries[0], root, 260)} |')
    if captured:
        lines.append(f'| {link("Complete contact sheet", "img/thumbnails/contact-sheet.jpg", root)} | {len(records)} | Complete visual inventory at overview scale. |')
    maps[root] = '\n'.join(lines) + '\n'

    for slug, label, entries in groups:
        sector_map = f'{base}/{slug}/README.md'
        lines = [f'# {label} — {heading.lower()}', '', explanation, '',
                 link('All sectors', root, sector_map) + ' · ' + link('Scenario library', 'scenarios/README.md', sector_map), '',
                 '```mermaid', 'flowchart LR', '  Sector[Sector] --> Scenario[Scenario folders]', '  Scenario --> Model[System and model]', '  Scenario --> View[Preview]', '```', '',
                 '| Scenario | Preview |', '| --- | --- |']
        for entry in entries:
            expected = scenario_asset_path(kind, entry)
            if entry['path'] != expected:
                raise ValueError(f'Noncanonical scenario image path: {entry["path"]}')
            scenario_map = dirname(expected) + '/README.md'
            lines.append(f'| {link(safe(entry["title"]), scenario_map, sector_map)}<br>`{entry["id"]}` | {picture(entry, sector_map, 360)} |')
            peer = scenario_asset_path('topologies' if captured else 'thumbnails', entry)
            preview_purpose = 'Actual fitted initial model state' if captured else 'Static declared `' + entry['view'] + '` view'
            local = [f'# {entry["title"]}', '', link(label, sector_map, scenario_map) + ' · ' + link('All sectors', root, scenario_map), '',
                     explanation, '', picture(entry, scenario_map, 900 if not captured else 720), '',
                     '```mermaid', 'flowchart LR', '  System[System definition] --> View[Preview]', ('  Model[Model assumptions] --> View' if captured else '  Symbols[Equipment symbols] --> View'), '```', '',
                     '| File or source | Purpose |', '| --- | --- |',
                     f'| {link("Preview", expected, scenario_map)} | {preview_purpose} |',
                     f'| {link("Scenario documentation", "scenarios/" + entry["id"] + "/README.md", scenario_map)} | Equipment roles, focused views and editable assumptions |',
                     f'| {link("System JSON", "scenarios/" + entry["system"], scenario_map)} | Equipment, ports, connections and layouts |',
                     f'| {link("Model JSON", "scenarios/" + entry["id"] + "/model.json", scenario_map)} | Replaceable behavior and initial values |',
                     f'| {link("Companion topology" if captured else "Captured model state", dirname(peer) + "/README.md", scenario_map)} | Another representation of this scenario |',
                     f'| {link("Generation metadata", manifest, scenario_map)} | Source and output provenance |', '']
            maps[scenario_map] = '\n'.join(local)
        maps[sector_map] = '\n'.join(lines) + '\n'
    return maps
