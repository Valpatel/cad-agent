        '| [system.json](system.json) | Equipment identities/types/variants, ports, connections, focused layouts, bindings, controls and provenance |',
        '| [model.json](model.json) | Versioned initial state, editable parameters and scenario/component assumptions |',
        f'| [../index.json](../index.json) | The `{sid}` catalog entry: discovery metadata and experiment command recipes |',
        '',
        f"Use the [v{model['version']} model schema]({schema}) and matching runtime validator when editing.",
