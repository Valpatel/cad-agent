"""Generate the scenario index and per-scenario README maps from canonical JSON.

Uses only Python's standard library. --check never creates, updates or removes
files. All source definitions and output claims are validated before any writes.
This owns only scenarios/README.md and catalog-listed scenario README.md files.
It does not generate assets, prune folders, modify models or publish a website.
"""
