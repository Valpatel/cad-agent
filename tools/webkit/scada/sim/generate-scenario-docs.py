OWNER_URL = 'https://github.com/Valpatel/cad-agent/blob/dev/tools/webkit/scada/sim/generate-scenario-docs.py'
MARKER = '<!-- Generated by tools/webkit/scada/sim/generate-scenario-docs.py -->'
OUTPUT_MODE = 0o644

def generated_note(catalog_path):
    return MARKER + '\n\nGenerated scenario map. Edit the [canonical JSON catalog](' + catalog_path + ') or the local system/model JSON for facts; edit the [documentation generator](' + OWNER_URL + ') for layout. Run `npm --prefix tools/webkit/scada run docs:scenarios` from the source repository. Check freshness with `npm --prefix tools/webkit/scada run docs:scenarios:check`; do not hand-edit this output.'

def fail(message):
    raise ValueError(message)

def safe_path(base, relative, *, required=False, file=False):
    """Reject symlinks in every path segment, including the selected owner root."""
    relative = Path(relative)
    if relative.is_absolute() or any((p in ('..', '.') for p in relative.parts)):
        fail(f'Unsafe owner-relative path: {relative}')
    target = base / relative
    for path in [*reversed(target.parents), target]:
        if path.is_symlink():
            fail(f'Symlinks are not allowed: {path}')
    if required and (not target.exists()):
        fail(f'Missing input: {target}')
    if target.exists() and file and (not target.is_file()):
        fail(f'Expected a regular file: {target}')
    return target

def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            fail(f'Duplicate JSON key: {key}')
        result[key] = value
    return result

def read_json(base, relative):
    path = safe_path(base, relative, required=True, file=True)
    try:
        value = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique_object, parse_constant=lambda token: fail(f'Invalid JSON number: {token}'))
        if not isinstance(value, dict):
            fail('Expected a JSON object')
        return value
    except (ValueError, UnicodeError) as error:
        fail(f'Invalid JSON in {relative}: {error}')

def unique_ids(records, label):
    if not isinstance(records, list):
        fail(f'{label} must be an array')
    ids = []
    for item in records:
        if not isinstance(item, dict) or not isinstance(item.get('id'), str) or (not item['id']):
            fail(f'{label} needs nonempty string IDs')
        if item['id'] in ids:
            fail(f"Duplicate {label} ID: {item['id']}")
        ids.append(item['id'])
    return set(ids)

def preflight(base):
    catalog = read_json(base, 'scenarios/index.json')
    if catalog.get('format') != 'scada-scenario-catalog' or catalog.get('version') != 1:
        fail('Expected scada-scenario-catalog version 1')
    entries = catalog.get('scenarios')
    unique_ids(entries, 'scenario')
    scenario_sector_groups(entries)
    if not entries:
        fail('Scenario catalog is empty')
    results = []
    claims = {'scenarios/README.md'}
    for entry in entries:
        sid = entry['id']
        if not re.fullmatch('[a-z0-9]+(?:-[a-z0-9]+)*', sid):
            fail(f'Unsafe scenario ID: {sid}')
        for field in ('system', 'model'):
            if entry.get(field) != f'{sid}/{field}.json':
                fail(f'Unexpected {field} path for {sid}')
        for field in ('title', 'sector', 'description'):
            if not isinstance(entry.get(field), str) or not entry[field].strip():
                fail(f'Missing {field} for {sid}')
        system = read_json(base, 'scenarios/' + entry['system'])
        model = read_json(base, 'scenarios/' + entry['model'])
        if system.get('format') != 'scada-system' or system.get('version') != 1:
            fail(f'Unsupported system contract: {sid}')
        if model.get('format') != 'scada-placeholder-model' or model.get('version') not in (1, 2):
            fail(f'Unsupported model contract: {sid}')
        if model.get('scenarioId') != sid or system.get('system', {}).get('id') != sid:
            fail(f'Scenario identity mismatch: {sid}')
        components = unique_ids(system.get('components'), f'{sid} component')
        if not isinstance(model.get('components'), dict) or set(model['components']) != components:
            fail(f'System/model component IDs differ: {sid}')
        connections = unique_ids(system.get('connections'), f'{sid} connection')
        for edge in system['connections']:
            if any((edge.get(side, {}).get('component') not in components for side in ('from', 'to'))):
                fail(f"Unknown connection endpoint: {sid}/{edge['id']}")
        unique_ids(system.get('views'), f'{sid} view')
        if not system['views']:
            fail(f'No views: {sid}')
        for view in system['views']:
            placements = [p['component'] for p in view['placements']]
            if len(set(placements)) != len(placements) or not set(placements) <= components:
                fail(f"Invalid view placements: {sid}/{view['id']}")
            if any((r['connection'] not in connections for r in view.get('routes', []))):
                fail(f"Invalid view connection: {sid}/{view['id']}")
        unique_ids(entry.get('experiments', []), f'{sid} experiment')
        for experiment in entry.get('experiments', []):
            for command in experiment['commands']:
                equipment = command.get('arguments', {}).get('equipment')
                if equipment is not None and equipment not in components:
                    fail(f"Unknown experiment equipment: {sid}/{experiment['id']}")
        output = f'scenarios/{sid}/README.md'
        if output in claims:
            fail(f'Duplicate output claim: {output}')
        claims.add(output)
        results.append((entry, system, model))
    for claim in sorted(claims):
        safe_path(base, claim, file=True)
    return results

def cell(x):
    return str(x).replace('|', '\\|').replace('\n', ' ')

def value(x):
    return json.dumps(x, ensure_ascii=False, separators=(',', ':'))

def command(c):
    a = c.get('arguments', {})
    bits = []
    for k, v in a.items():
        bits.append(f'{k}={value(v)}')
    return '`' + c['action'] + '(' + ', '.join(bits) + ')`'

