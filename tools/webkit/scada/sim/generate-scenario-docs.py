def render_index(records):
    groups = collections.OrderedDict()
    versions = collections.Counter()
    for entry, system, model in records:
        groups.setdefault(entry['sector'], []).append((entry, system, model))
        versions[model['version']] += 1
    summary = f'The {len(records)} scenario folders pair a UI system description with a separate illustrative\nmodel. Model contracts: ' + '; '.join((f'v{version}: {count}' for version, count in sorted(versions.items()))) + '. Every focused view\nwithin a scenario observes the same model session.\n'
    intro = INDEX_INTRO.replace('{generated_note}', generated_note('index.json')).replace('{version_summary}', summary)
    lines = [intro.rstrip(), '']
    for sector, entries in groups.items():
        lines += [f'### {sector}', '', '| Scenario map | Model | Equipment / views | Preview |', '| --- | --- | --- | --- |']
        for entry, system, model in entries:
            sid = entry['id']
            lines.append(f'''| [{cell(entry['title'])}]({sid}/README.md) | v{model['version']} | {len(system['components'])} / {len(system['views'])} | <a href="../{scenario_asset_path('thumbnails', entry)}"><img src="../{scenario_asset_path('thumbnails', entry)}" width="180" alt="{html.escape(entry['title'], quote=True)} preview"></a> |''')
        lines.append('')
    lines.append(INDEX_FOOTER.rstrip())
    return '\n'.join(lines) + '\n'

def generate(base, *, check=False):
    base = Path(os.path.abspath(base))
    safe_path(base, '', required=True)
    records = preflight(base)
    outputs = {'scenarios/README.md': render_index(records)}
    for entry, system, model in records:
        outputs[f"scenarios/{entry['id']}/README.md"] = render_scenario(entry, system, model)
    stale = []
    for relative, content in outputs.items():
        path = safe_path(base, relative, file=True)
        # npm preserves member modes. Normalize existing matching outputs too,
        # so a restrictive extraction umask cannot change release tarball bytes.
        if not path.exists() or path.read_bytes() != content.encode('utf-8') or path.stat().st_mode & 0o7777 != OUTPUT_MODE:
            stale.append(relative)
    if check and stale:
        fail('Stale scenario documentation: ' + ', '.join(stale) + '. Run npm --prefix tools/webkit/scada run docs:scenarios.')
    if not check:
        for relative in stale:
            target = safe_path(base, relative, file=True)
            with tempfile.NamedTemporaryFile(dir=target.parent, prefix='.scenario-docs-', delete=False) as temp:
                temporary = Path(temp.name)
                try:
                    temp.write(outputs[relative].encode('utf-8'))
                    temp.flush()
                    os.fchmod(temp.fileno(), OUTPUT_MODE)
                except BaseException:
                    temporary.unlink(missing_ok=True)
                    raise
            try:
                os.replace(temporary, target)
            finally:
                temporary.unlink(missing_ok=True)
    return {'scenarios': len(records), 'outputs': len(outputs), 'changed': len(stale), 'check': check}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Report stale documentation without writing')
    parser.add_argument('--package-root', type=Path, default=SIM, help="Explicit owner root for isolated fixtures; defaults to this script's package")
    args = parser.parse_args()
    try:
        result = generate(args.package_root, check=args.check)
    except (ValueError, OSError, KeyError, TypeError) as error:
        print(f'Scenario documentation: {error}', file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0
if __name__ == '__main__':
    raise SystemExit(main())
